"""The data of the importance-weighting experiment, with exact truth for every row. No learning and no BCA code here.

Spec version 5: every log is made at one of five dataset qualities (world.QUALITIES: random, medium-replay, medium,
medium-expert, expert): version 4's recording controller with a random share per episode (world.random_share). The
expert quality is version 4's data bit for bit.

Per quality and data seed k (0-4), every stream is np.random.default_rng([20261016, k, tag]) (TAGS below); one
generator per log gives its starts, then the noise (episodes, 100, 4), then the coin (episodes, 100) (version 4's),
then r (episodes, 100, 4), m (episodes, 100) and the pick (episodes,) (world.draw_episodes with the quality):
  training-law log   1,000 episodes x 100 steps from the training law (lam = -2), v1's layout: episodes 0-499 train
                     (split 0), 500-699 calibration (split 1; the calibration bank takes 5 rows of each through
                     calibration/bank.stratified_bank), 700-999 held out (split 2), which is also the "none" test log
  test logs          300 episodes per tilted law ("mild" lam = 0, "strong" lam = +2); split 2 (never trained on)
  classifier samples 300 episodes per law (train, mild, strong) plus a second, independent training-law sample
                     (train2) for the no-tilt control: observations, recorded commands and episode ids only
  the ball           the expert's ball of the same seed, for every quality (expert_ball): v1's densest-15% rule
                     (experiments.shift.shift.define_gap) on the expert's training-law log, which is version 4's log;
                     every quality's build simulates that log itself, so the qualities build independently
  quadrature         per-current curves on 41 currents x 2,000 episodes, integrated against each law: Z, in-ball and
                     hold shares per law, holds removed, gapped test mass per tilt (world.quadrature). Twice: the
                     expert's (version 4's; mark D1 is judged on it, the same in every quality) and the quality's own
                     (its single threshold's test mass; r, m and the pick from tag 11). For the expert they are one.
  truth rows         5,000 held-out steps outside the ball (mark M2's rows), with truth.noise_map (target-noise spread
                     of a perfect critic; a control with no critic-error information). The exact values M2 needs,
                     of the host's own policy, come later from learners.exact_q.
Shared by all qualities, seeds and controllers: start banks of 1,000 fixed starts per law (default_rng([20261016,
1000]); the three banks share every float and wave number, only c differs), and their anchors: the random quality on
fixed streams (default_rng([20261016, 1002]): noise, coin, r, m; start j has pick j mod 500, so each pick is used twice
and a mixture's points are its expected points over the plan) is 0 points, the stall-aware controller 100 points. Every
quality with and without the hold, and the zero command, are reference rows.

Rows are generated by thruster_chain.dynamics (the function env.step calls; batch-independent by construction) and the
build replays every row of every log through env.step (reset(options={'state'}) + step) and records the mismatches,
which must be 0. Commands are rounded to float32 first, as env.step does.

Arrays of a log (D4RL field names, as v1's dataset.Log): observations, actions, rewards (float32), next_observations,
terminals (all False), timeouts (t = 99); infos/state, infos/next_state, infos/reward64 (exact float64), infos/episode,
infos/t, infos/split; diagnostics infos/hold, infos/hard_water and infos/random (the controller's own flags: log[key]
refuses them, only log.diagnostic(key) returns them); truth/in_ball (command inside the seed's ball) and
truth/weight_<tilt> = p_tilt(c) / p_train(c) (closed form, c = infos/state[:, 10]). The meta holds the quality and
each episode's pick and random share.
IWLog has v1's Log interface, so shift.make_removal, learners.normalization and learners.prepare take it unchanged.

Files (HDF5 without timestamps, so a rebuild gives the same bytes; a <file>.manifest.json beside each holds the SHA-256
of the file, of every array, the build settings and the SHA-256 of the code; reading verifies every hash):
  <root>/start_banks/start_banks.hdf5 (+ start_banks.json)   shared by every quality
  <root>/<quality>/data/seed<k>/train_law.hdf5, test_mild.hdf5, test_strong.hdf5, samples.hdf5, truth.hdf5
  <root>/<quality>/data/seed<k>/world.json (+ .sha256)  the ball, the removal, both quadratures, mark D1, replay, hashes
  <root>/<quality>/data/seed<k>/build.json              timings (not hashed; the only non-deterministic file)
Run: python -m experiments.shift_iw.data --quality expert --seeds 0 1 2 3 4 [--size full|small] [--out ROOT]
"""

