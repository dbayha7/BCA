def main(argv=None):
    p = argparse.ArgumentParser(description="Build the importance-weighting data (no learning, no BCA).")
    p.add_argument("--quality", choices=W.QUALITIES, required=True)
    p.add_argument("--seeds", type=int, nargs="+", required=True)
    p.add_argument("--size", choices=sorted(SIZES), default="full")
    p.add_argument("--out", default=str(OUT_DEFAULT), help="the shared root (start banks and one folder per quality)")
    p.add_argument("--no-start-banks", action="store_true")
    a = p.parse_args(argv)
    sizes = SIZES[a.size]
    out = refuse_protected(a.out)
    if not a.no_start_banks:
        s = time.perf_counter()
        build_start_banks(banks_dir(out), sizes.start_bank)
        print(f"start banks: {time.perf_counter() - s:.1f}s", flush=True)
    for seed in a.seeds:
        build_seed(seed, data_dir(out, a.quality), sizes, a.quality, log=lambda m: print(m, flush=True))


if __name__ == "__main__":
    sys.exit(main())
