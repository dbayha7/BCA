def sha256_file(path):
    return DS.sha256_file(path)


def sha256_array(x):
    return DS.sha256_array(x)


def code_hashes():
    here = Path(__file__).parent
    out = {f"experiments/shift_iw/{n}": sha256_file(here / n) for n in CODE_FILES_IW}
    out.update({n: sha256_file(REPO / n) for n in CODE_FILES_REPO})
    return out


def spec_sha256():
    """SHA-256 of iw/spec.json (the pre-registration), or None when it is not beside this package."""
    return sha256_file(SPEC_JSON) if SPEC_JSON.is_file() else None


def write_hdf5(path, arrays, meta, about):
    """Arrays (name -> array; '/' makes groups) to an HDF5 file without timestamps, and a manifest beside it
    (path + '.manifest.json') with the SHA-256 of the file and of every array, the meta and the code hashes."""
    import h5py

    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with h5py.File(path, "w", libver="earliest") as f:
        for key in sorted(arrays):
            f.create_dataset(key, data=np.asarray(arrays[key]), track_times=False)
        f.attrs["schema"] = SCHEMA
        f.attrs["about"] = about
        f.attrs["meta"] = json.dumps(meta, sort_keys=True)
    manifest = dict(schema=SCHEMA, file=path.name, file_sha256=sha256_file(path), about=about,
                    arrays={k: dict(sha256=sha256_array(v), dtype=str(np.asarray(v).dtype),
                                    shape=list(np.asarray(v).shape)) for k, v in sorted(arrays.items())},
                    meta=meta, code_sha256=code_hashes(), spec_sha256=spec_sha256())
    Path(str(path) + ".manifest.json").write_text(json.dumps(manifest, sort_keys=True, indent=1))
    return manifest


def read_hdf5(path):
    """(arrays, meta) of a file written by write_hdf5, after verifying the file and every array against its manifest
    (ValueError on any mismatch)."""
    import h5py

    path = Path(path)
    manifest = json.loads(Path(str(path) + ".manifest.json").read_text())
    if sha256_file(path) != manifest["file_sha256"]:
        raise ValueError(f"{path}: file SHA-256 does not match its manifest")
    with h5py.File(path, "r") as f:
        arrays = {k: f[k][()] for k in manifest["arrays"]}
        meta = json.loads(f.attrs["meta"])
    for k, v in arrays.items():
        if sha256_array(v) != manifest["arrays"][k]["sha256"]:
            raise ValueError(f"{path}: array {k} does not match its manifest SHA-256")
    if meta != manifest["meta"]:
        raise ValueError(f"{path}: meta differs from its manifest")
    return arrays, meta


def write_json(path, value):
    """JSON with a sha256sum-style sidecar (path + '.sha256'). Returns the file's SHA-256."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, sort_keys=True, indent=1, allow_nan=False))
    digest = sha256_file(path)
    Path(str(path) + ".sha256").write_text(f"{digest}  {path.name}\n")
    return digest


def read_json(path):
    path = Path(path)
    side = Path(str(path) + ".sha256")
    if side.is_file() and side.read_text().split()[0] != sha256_file(path):
        raise ValueError(f"{path}: SHA-256 does not match its sidecar")
    return json.loads(path.read_text())


