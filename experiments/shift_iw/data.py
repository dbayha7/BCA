def check_quality(quality):
    if quality not in W.QUALITIES:
        raise ValueError(f"unknown quality {quality!r}; one of {', '.join(W.QUALITIES)}")
    return quality


def training_law_log(seed, sizes=FULL, quality="expert"):
    """A quality's training-law log (with its bank rows), without truth columns."""
    E = sum(sizes.split_sizes)
    sim = W.draw_episodes(E, np.random.default_rng([W.MASTER_SEED, int(seed), TAGS["train_law"]]), "train",
                          W.HoldRecorder(), quality=check_quality(quality))
    bank = calibration_bank(seed, sizes.calibration, sizes.train, sizes.bank_rows_per_episode)
    return make_log(sim, seed, "train", sizes.split_sizes, bank, TAGS["train_law"], quality)


def generate_logs(seed, sizes=FULL, quality="expert"):
    """A quality's training-law log (with its bank rows) and two test logs, without truth columns."""
    rec = W.HoldRecorder()
    train_log = training_law_log(seed, sizes, quality)
    tests = {}
    for tilt in ("mild", "strong"):
        tag = TAGS[f"test_{tilt}"]
        s = W.draw_episodes(sizes.test, np.random.default_rng([W.MASTER_SEED, int(seed), tag]), tilt, rec,
                            quality=quality)
        tests[tilt] = make_log(s, seed, tilt, (0, 0, sizes.test), (), tag, quality)
    return train_log, tests


def expert_ball(seed, sizes=FULL):
    """The ball of every quality of a seed (spec version 5): v1's densest-15% rule (shift.define_gap) on the training
    split of the expert's training-law log, which is version 4's log bit for bit. Returns (Gap, record)."""
    return SH.define_gap(training_law_log(seed, sizes, "expert"))


def classifier_samples(seed, sizes=FULL, quality="expert"):
    """Per sample name (train, mild, strong, train2): observations (float32), recorded commands (float32) and episode
    ids of `sizes.sample` episodes of its law at the quality. Nothing else (no rewards, next states or values)."""
    rec = W.HoldRecorder()
    check_quality(quality)
    out = {}
    for name, law in SAMPLE_LAWS.items():
        rng = np.random.default_rng([W.MASTER_SEED, int(seed), TAGS[f"sample_{name}"]])
        sim = W.draw_episodes(sizes.sample, rng, law, rec, quality=quality)
        E, L = sim["commands"].shape[:2]
        out[name] = dict(observations=sim["states"][:, :-1].astype(np.float32).reshape(E * L, TC.DX),
                         actions=sim["commands"].reshape(E * L, TC.DA),
                         episode=np.repeat(np.arange(E, dtype=np.int32), L))
    return out


def truth_rows(log, sizes=FULL, seed=None):
    """Mark M2's rows: `sizes.truth_rows` held-out (split 2) steps whose command lies outside the ball, drawn by
    default_rng([20261016, seed, 10]) and sorted, and the noise map at them."""
    seed = log.meta["seed"] if seed is None else seed
    held = log.split_rows("evaluation")
    held = held[~log["truth/in_ball"][held]]
    rng = np.random.default_rng([W.MASTER_SEED, int(seed), TAGS["truth_rows"]])
    rows = np.sort(rng.choice(held, min(sizes.truth_rows, len(held)), replace=False))
    x = log["infos/state"][rows]
    a = np.asarray(log["actions"][rows], np.float64)
    nm = TR.noise_map(x, a, W.PHYSICS, horizon=sizes.noise_map_horizon)
    return {"rows": rows.astype(np.int64), "noise_map": nm}


def d1(quad):
    """Mark D1 (spec.json) on one seed's quadrature of the expert (the ball every quality shares): values, ranges and
    pass."""
    checks = dict(
        holds_removed=dict(value=quad["holds_removed_train"]["value"], rule=f">= {D1_HOLDS_REMOVED_MIN}",
                           ok=quad["holds_removed_train"]["value"] >= D1_HOLDS_REMOVED_MIN),
        Z=dict(value=quad["Z"]["value"], rule=f"in {list(D1_Z)}", ok=D1_Z[0] <= quad["Z"]["value"] <= D1_Z[1]))
    for tilt, (lo, hi) in D1_IN_BALL.items():
        v = quad["in_ball_share"][tilt]["value"]
        checks[f"in_ball_{tilt}"] = dict(value=v, rule=f"in {[lo, hi]}", ok=lo <= v <= hi)
    return dict(checks=checks, passes=all(c["ok"] for c in checks.values()),
                note="judged on each seed's quadrature of the expert, the ball every quality shares (spec.json "
                     "pass_marks D1)")


def removal_summary(log, gap):
    """What the ball removes: kept rows, leaks (kept rows inside the ball: 0) and, from the diagnostic flags, the share
    of the training split's holds it removes, the random share, the hard-water rows kept, and what remains near 80%:
    kept rows with thruster 1 at or below -0.75 (share, and how many are not random commands) and kept rows at exactly
    float32(-0.8) (each a hold the ball missed: on steps that are not random, normal driving never reaches 80%)."""
    removal = SH.make_removal(log, "gap", gap)
    kept = removal.kept_train_rows(log)
    bank = removal.bank_rows(log)
    train = log.split_rows("train")
    hold = log.diagnostic("infos/hold")
    hard = log.diagnostic("infos/hard_water")
    rand = log.diagnostic("infos/random")
    ing = log["truth/in_ball"]
    t1 = np.asarray(log["actions"][:, 0])
    near = t1 <= NEAR_LIMIT
    exact80 = t1 == -W.KNEE32
    return dict(training_rows=int(len(train)), kept_training_rows=int(len(kept)),
                kept_share=float(len(kept) / len(train)), bank_rows=int(len(log.bank_rows)),
                kept_bank_rows=int(len(bank)), leaks_training=SH.leak_count(kept, log, gap),
                leaks_bank=SH.leak_count(bank, log, gap),
                hold_share_training=float(hold[train].mean()),
                random_share_training=float(rand[train].mean()),
                holds_removed_training=float(ing[train][hold[train]].mean()) if hold[train].any() else None,
                removed_that_are_holds=float(hold[train][ing[train]].mean()) if ing[train].any() else None,
                hard_water_rows_kept=float((~ing[train][hard[train]]).mean()) if hard[train].any() else None,
                kept_near_limit_share=float(near[kept].mean()) if len(kept) else None,
                kept_near_limit_not_random=int((near[kept] & ~rand[kept]).sum()),
                kept_at_exactly_80=int(exact80[kept].sum()),
                kept_at_exactly_80_not_hold=int((exact80[kept] & ~hold[kept]).sum()),
                held_out_in_ball_share=float(ing[log.split_rows("evaluation")].mean()))


def quality_plan_record(quality):
    """The quality's plan as world.json records it."""
    rules = {"random": "1", "medium-replay": "1 - 0.35 pick / 499", "medium": "0.65",
             "medium-expert": "0.65 if pick < 250, else 0", "expert": "0"}
    return dict(quality=quality, random_share=rules[quality], plan=W.QUALITY_PLAN.as_dict(),
                rule="each step: if m < eps the command is r, uniform on [-1, 1)^4, and never a hold; otherwise version "
                     "4's recording controller (world.with_random); eps per episode from its pick only")


def build_seed(seed, out, sizes=FULL, quality="expert", log=print):
    """Build and write one seed's files of a quality (module docstring) into out/seed<k> (out: the quality's data
    directory). Returns (world record, timings)."""
    check_quality(quality)
    t0, times = time.perf_counter(), {}
    tick = lambda name, start: times.__setitem__(name, round(time.perf_counter() - start, 2))
    out = refuse_protected(out) / f"seed{int(seed)}"
    s = time.perf_counter()
    train_log, tests = generate_logs(seed, sizes, quality)
    tick("logs", s)
    s = time.perf_counter()
    gap, record = expert_ball(seed, sizes)
    tick("ball", s)
    if gap is None:
        raise RuntimeError(f"seed {seed}: the removal rule found no ball ({record.get('reason')})")
    train_log = train_log.with_arrays(truth_columns(train_log, gap))
    tests = {k: v.with_arrays(truth_columns(v, gap)) for k, v in tests.items()}
    s = time.perf_counter()
    samples = classifier_samples(seed, sizes, quality)
    tick("classifier_samples", s)
    s = time.perf_counter()
    quad_seed = (W.MASTER_SEED, int(seed), TAGS["quadrature"])
    grid, curve_x = W.curves(gap, sizes.grid_points, sizes.per_point, quad_seed)
    quad_x = W.quadrature(grid, curve_x)
    if quality == "expert":
        curve, quad = curve_x, quad_x
    else:
        _, curve = W.curves(gap, sizes.grid_points, sizes.per_point, quad_seed, quality=quality,
                            random_seed=(W.MASTER_SEED, int(seed), TAGS["quadrature_random"]))
        quad = W.quadrature(grid, curve)
    tick("quadrature", s)
    s = time.perf_counter()
    truth = truth_rows(train_log, sizes, seed)
    tick("truth_rows", s)
    s = time.perf_counter()
    replays = {"train_law": replay(train_log)}
    for k, v in tests.items():
        replays[f"test_{k}"] = replay(v)
    tick("replay", s)
    if any(r["mismatches"] for r in replays.values()):
        raise AssertionError(f"seed {seed}: replay through env.step mismatched: {replays}")
    s = time.perf_counter()
    files = {}
    about = "ThrusterChain importance-weighting log (bca-shift-work/iw/SPEC.md); see experiments/shift_iw/data.py"
    m = write_hdf5(out / "train_law.hdf5", train_log._arrays, train_log.meta, about + "; training law, all splits")
    files["train_law.hdf5"] = m["file_sha256"]
    for k, v in tests.items():
        m = write_hdf5(out / f"test_{k}.hdf5", v._arrays, v.meta, about + f"; test law '{k}'")
        files[f"test_{k}.hdf5"] = m["file_sha256"]
    flat = {f"{name}/{f}": arr for name, d in samples.items() for f, arr in d.items()}
    m = write_hdf5(out / "samples.hdf5", flat, dict(schema=SCHEMA, seed=int(seed), quality=quality, laws=SAMPLE_LAWS,
                                                    episodes=sizes.sample, gap=gap.as_dict()),
                   "classifier samples: observations, recorded commands and episode ids only")
    files["samples.hdf5"] = m["file_sha256"]
    m = write_hdf5(out / "truth.hdf5", truth, dict(schema=SCHEMA, seed=int(seed), quality=quality,
                                                   sizes=sizes.as_dict()),
                   "mark M2's held-out rows outside the ball and the noise map")
    files["truth.hdf5"] = m["file_sha256"]
    tick("write", s)
    curve_summary = lambda cv: dict(grid=grid.tolist(), **{k: dict(mean=v.mean(1).tolist(),
                                                                   se=(v.std(1, ddof=1) / math.sqrt(v.shape[1])).tolist())
                                                          for k, v in cv.items()})
    in_ball_steps = {"none": int(train_log["truth/in_ball"][train_log.split_rows("evaluation")].sum()),
                     **{k: int(v["truth/in_ball"].sum()) for k, v in tests.items()}}
    world = dict(
        schema=SCHEMA, seed=int(seed), quality=quality, quality_plan=quality_plan_record(quality),
        sizes=sizes.as_dict(), master_seed=W.MASTER_SEED, tags=TAGS,
        laws={t: dict(lam=W.law_lambda(t), mean_current=W.mean_current(t), weight_constant=W.ratio_constant(t),
                      weight_slope=W.ratio_slope(t), full_test_mass=W.full_test_mass(t)) for t in W.TILT_NAMES},
        recorder=W.HOLD_SPEC.as_dict(), hold_command=W.HoldRecorder().hold.tolist(),
        ball_source=BALL_SOURCE, gap=gap.as_dict(), gap_record=record, removal=removal_summary(train_log, gap),
        test_in_ball_share={"none": float(train_log["truth/in_ball"][train_log.split_rows("evaluation")].mean()),
                            **{k: float(v["truth/in_ball"].mean()) for k, v in tests.items()}},
        test_in_ball_steps=in_ball_steps,
        quadrature=quad, curves=curve_summary(curve),
        quadrature_expert=quad_x, curves_expert=curve_summary(curve_x),
        D1=d1(quad_x), replay=replays, files=files, code_sha256=code_hashes(), spec_sha256=spec_sha256())
    digest = write_json(out / "world.json", world)
    times["total"] = round(time.perf_counter() - t0, 2)
    (out / "build.json").write_text(json.dumps(dict(seed=int(seed), quality=quality, seconds=times,
                                                    world_json_sha256=digest), indent=1))
    log(f"{quality} seed {seed}: {train_log.n_rows} training-law rows, expert's ball rho {gap.rho:.3f}, "
        f"Z {quad['Z']['value']:.4f} (expert {quad_x['Z']['value']:.4f}), "
        f"D1 {'pass' if world['D1']['passes'] else 'FAIL'}, {times['total']:.0f}s")
    return world, times


# ------------------------------------------------------------------------------------------------ start banks

def start_banks(n=1000):
    """The fixed start banks: n starts per law from one generator (default_rng([20261016, 1000])) re-drawn per law,
    so the banks share every float and wave number and differ only in c."""
    return {t: W.draw_starts(int(n), np.random.default_rng(list(START_BANK_STREAM)), t) for t in W.TILT_NAMES}


class ZeroCommand:
    """The zero command on every thruster (a reference row on the start banks)."""

    name = "the zero command"

    def __call__(self, x):
        return np.zeros(np.shape(x)[:-1] + (TC.DA,))


def bank_streams(n=1000):
    """The fixed controller streams on the start banks (default_rng([20261016, 1002]): noise (n, 100, 4), coin
    (n, 100), r (n, 100, 4), m (n, 100), the same on every bank and for every quality) and the balanced picks
    pick_j = j mod 500 (each pick used exactly twice over 1,000 starts; not drawn)."""
    rng = np.random.default_rng(list(CONTROLLER_BANK_STREAM))
    noise = rng.standard_normal((int(n), W.LENGTH, TC.DA))
    coin = rng.uniform(size=(int(n), W.LENGTH))
    r = rng.uniform(-1.0, 1.0, size=(int(n), W.LENGTH, TC.DA))
    m = rng.uniform(size=(int(n), W.LENGTH))
    return noise, coin, r, m, np.arange(int(n)) % W.QUALITY_PLAN.picks


def quality_on_bank(quality, n=1000, hold=True):
    """A quality's controller on a start bank of n starts with the fixed streams (bank_streams); hold=False is the same
    controller driving normally instead of holding (hold probability 0)."""
    noise, coin, r, m, pick = bank_streams(n)
    rec = W.HoldRecorder() if hold else W.HoldRecorder(replace(W.HOLD_SPEC, hold_probability=0.0))
    return W.StreamedQuality(rec, noise, coin, r, m, W.random_share(quality, pick),
                             f"{quality}{'' if hold else ' without the hold'} (fixed streams)")


def anchors(banks):
    """Mean 100-step return (exact; truth.rollout) of the fixed controllers on each bank, with standard errors and
    points: the random quality (0 points), the stall-aware controller (100 points), and as reference rows every quality
    with and without the hold and the zero command. Returns {law: dict(controllers, anchor=dict(random, top))}."""
    out = {}
    for law, x0 in banks.items():
        n = len(x0)
        ctrls = {"stall_aware": RC.stall_aware(W.PHYSICS), "zero_command": ZeroCommand()}
        for q in W.QUALITIES:
            ctrls[q] = quality_on_bank(q, n, hold=True)
            ctrls[f"{q} without the hold"] = quality_on_bank(q, n, hold=False)
        rows = {}
        for name, ctrl in ctrls.items():
            J = TR.rollout(ctrl, x0, W.PHYSICS).J
            rows[name] = dict(mean=float(J.mean()), se=float(J.std(ddof=1) / math.sqrt(n)) if n > 1 else None)
        anchor = dict(random=rows["random"]["mean"], top=rows["stall_aware"]["mean"])
        for row in rows.values():
            row["points"] = float(W.points(row["mean"], anchor))
            row["points_se"] = None if row["se"] is None else 100.0 * row["se"] / (anchor["top"] - anchor["random"])
        out[law] = dict(controllers=rows, anchor=anchor)
    return out


def build_start_banks(out, n=1000, log=print):
    """The shared start banks and their anchors in `out` (the root's start_banks directory)."""
    out = refuse_protected(out)
    banks = start_banks(n)
    m = write_hdf5(out / "start_banks.hdf5", {f"starts/{k}": v for k, v in banks.items()},
                   dict(schema=SCHEMA, n=int(n), stream=list(START_BANK_STREAM),
                        controller_stream=list(CONTROLLER_BANK_STREAM), picks="pick_j = j mod 500"),
                   "fixed evaluation starts per law, shared by every quality, seed and controller")
    record = dict(schema=SCHEMA, n=int(n), file_sha256=m["file_sha256"], anchors=anchors(banks),
                  controller_stream=list(CONTROLLER_BANK_STREAM), picks="pick_j = j mod 500",
                  points_rule="100 (J - J_random) / (J_stall_aware - J_random) per law (world.points)",
                  rounding="the qualities' commands are rounded to float32, as in their logs; the stall-aware "
                           "controller, the zero command and learned actors are rolled out as in version 4")
    write_json(out / "start_banks.json", record)
    log("start banks: " + ", ".join(f"{k} {v['anchor']['random']:.2f} / {v['anchor']['top']:.2f}"
                                    for k, v in record["anchors"].items()))
    return record


