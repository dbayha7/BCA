"""The data of the importance-weighting experiment, with exact truth for every row. No learning and no BCA code here.

Per data seed k (0-4), every stream is np.random.default_rng([20261016, k, tag]) (TAGS below); one generator per log
gives its starts, then the noise (episodes, 100, 4), then the coin (episodes, 100):
  training-law log   1,000 episodes x 100 steps from the training law (lam = -2), v1's layout: episodes 0-499 train
                     (split 0), 500-699 calibration (split 1; the calibration bank takes 5 rows of each through
                     calibration/bank.stratified_bank), 700-999 held out (split 2), which is also the "none" test log
  test logs          300 episodes per tilted law ("mild" lam = 0, "strong" lam = +2); split 2 (never trained on)
  classifier samples 300 episodes per law (train, mild, strong) plus a second, independent training-law sample
                     (train2) for the no-tilt control: observations, recorded commands and episode ids only
  the ball           v1's densest-15% rule on the training split (experiments.shift.shift.define_gap)
  quadrature         per-current curves on 41 currents x 2,000 episodes, integrated against each law: Z, in-ball and
                     hold shares per law, holds removed, gapped test mass per tilt (world.quadrature)
  truth rows         5,000 held-out steps outside the ball (mark M2's rows), with truth.noise_map (target-noise spread
                     of a perfect critic; a control with no critic-error information). The exact values M2 needs,
                     of the host's own policy, come later from learners.exact_q.
Shared by all seeds and controllers: start banks of 1,000 fixed starts per law (default_rng([20261016, 1000]); the
three banks share every float and wave number, only c differs), and their anchors: the recording controller with fixed
noise and coin streams (default_rng([20261016, 1001])) is 0 points, the stall-aware controller 100 points; normal
driving only is a reference row.

Rows are generated by thruster_chain.dynamics (the function env.step calls; batch-independent by construction) and the
build replays every row of every log through env.step (reset(options={'state'}) + step) and records the mismatches,
which must be 0. Commands are rounded to float32 first, as env.step does.

Arrays of a log (D4RL field names, as v1's dataset.Log): observations, actions, rewards (float32), next_observations,
terminals (all False), timeouts (t = 99); infos/state, infos/next_state, infos/reward64 (exact float64), infos/episode,
infos/t, infos/split; diagnostics infos/hold and infos/hard_water (the recording controller's own flags: log[key]
refuses them, only log.diagnostic(key) returns them); truth/in_ball (command inside the seed's ball) and
truth/weight_<tilt> = p_tilt(c) / p_train(c) (closed form, c = infos/state[:, 10]).
IWLog has v1's Log interface, so shift.make_removal, learners.normalization and learners.prepare take it unchanged.

Files (HDF5 without timestamps, so a rebuild gives the same bytes; a <file>.manifest.json beside each holds the SHA-256
of the file, of every array, the build settings and the SHA-256 of the code; reading verifies every hash):
  <out>/start_banks.hdf5 (+ start_banks.json)          shared
  <out>/seed<k>/train_law.hdf5, test_mild.hdf5, test_strong.hdf5, samples.hdf5, truth.hdf5
  <out>/seed<k>/world.json (+ world.json.sha256)       the ball, the removal, quadrature, mark D1, replay, file hashes
  <out>/seed<k>/build.json                             timings (not hashed; the only non-deterministic file)
Run: python -m experiments.shift_iw.data --seeds 0 1 2 3 4 [--size full|small] [--out DIR]
"""

