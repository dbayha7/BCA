class IWLog(Mapping):
    """A generated log with v1's dataset.Log interface (module docstring). log[key] refuses the recording controller's
    flags (DIAGNOSTIC_KEYS); diagnostic(key) returns them and counts the read (diagnostic_reads)."""

    def __init__(self, arrays, meta):
        missing = set(D4RL_KEYS + INFO_KEYS + DIAGNOSTIC_KEYS) - set(arrays)
        if missing:
            raise ValueError(f"log arrays missing: {sorted(missing)}")
        unknown = set(arrays) - set(LOG_KEYS)
        if unknown:
            raise ValueError(f"unknown log arrays: {sorted(unknown)}")
        self._arrays = {k: np.asarray(arrays[k]) for k in LOG_KEYS if k in arrays}
        for v in self._arrays.values():
            v.setflags(write=False)
        self.meta = dict(meta)
        self.diagnostic_reads = 0

    def __getitem__(self, key):
        if key in DIAGNOSTIC_KEYS:
            raise KeyError(f"{key} is the recording controller's own flag, a diagnostic only; no learner, removal rule "
                           "or scorer may read it (use IWLog.diagnostic)")
        return self._arrays[key]

    def __iter__(self):
        return (k for k in self._arrays if k not in DIAGNOSTIC_KEYS)

    def __len__(self):
        return sum(1 for k in self._arrays if k not in DIAGNOSTIC_KEYS)

    def diagnostic(self, key):
        if key not in DIAGNOSTIC_KEYS:
            raise KeyError(f"{key} is not a diagnostic array")
        self.diagnostic_reads += 1
        return self._arrays[key]

    def with_arrays(self, extra):
        """A new log with extra arrays (the truth columns) added."""
        return IWLog({**self._arrays, **extra}, self.meta)

    @property
    def n_rows(self):
        return int(len(self._arrays["actions"]))

    @property
    def physics(self):
        return TC.Physics(**self.meta["physics"])

    @property
    def spec(self):
        return W.HoldSpec(**self.meta["recorder"])

    @property
    def current(self):
        """c of every row (exact float64)."""
        return self._arrays["infos/state"][:, TC.CURRENT]

    def split_rows(self, split):
        return np.flatnonzero(self._arrays["infos/split"] == SPLITS.index(split))

    @property
    def bank_rows(self):
        """The calibration bank's rows before any removal (empty for a test log), ascending."""
        return np.asarray(self.meta.get("bank_rows", []), np.int64)

    def array_hashes(self):
        return {k: sha256_array(v) for k, v in self._arrays.items()}


def make_log(sim, seed, law, split_sizes, bank_rows=(), tag=None):
    """An IWLog from world.simulate output: splits by episode (split_sizes episodes of each split in order; a test
    log is all split 2)."""
    E, L = sim["commands"].shape[:2]
    if sum(split_sizes) != E:
        raise ValueError("split sizes must add up to the episodes")
    flat = lambda v: np.ascontiguousarray(v.reshape(E * L, *v.shape[2:]))
    S = sim["states"]
    obs = S.astype(np.float32)
    arrays = {
        "observations": flat(obs[:, :-1]), "actions": flat(sim["commands"]),
        "rewards": flat(sim["rewards"]).astype(np.float32), "next_observations": flat(obs[:, 1:]),
        "terminals": np.zeros(E * L, bool), "timeouts": np.tile(np.arange(L) == L - 1, E),
        "infos/state": flat(S[:, :-1]), "infos/next_state": flat(S[:, 1:]), "infos/reward64": flat(sim["rewards"]),
        "infos/episode": np.repeat(np.arange(E, dtype=np.int32), L),
        "infos/t": np.tile(np.arange(L, dtype=np.int32), E),
        "infos/split": np.repeat(np.repeat(np.arange(len(split_sizes), dtype=np.int8), split_sizes), L),
        "infos/hold": flat(sim["hold"]), "infos/hard_water": flat(sim["hard_water"]),
    }
    meta = dict(schema=SCHEMA, rep=int(seed), seed=int(seed), world="stall", law=law,
                law_lambda=W.law_lambda(law), env_id=ENV_ID, physics=W.PHYSICS.as_dict(), recorder=W.HOLD_SPEC.as_dict(),
                episodes=int(E), length=int(L), split_sizes=[int(s) for s in split_sizes],
                stream=[W.MASTER_SEED, int(seed), int(tag)] if tag is not None else None,
                bank_rows=[int(r) for r in bank_rows], gymnasium_version=gym.__version__)
    return IWLog(arrays, meta)


def truth_columns(log, gap):
    """truth/in_ball (the seed's ball) and truth/weight_<tilt> (closed form in c)."""
    out = {"truth/in_ball": gap.contains(log["actions"])}
    for tilt in W.TILT_NAMES:
        out[f"truth/weight_{tilt}"] = W.ratio(log.current, tilt)
    return out


def calibration_bank(seed, calibration_episodes, first_episode, rows_per_episode=5, length=W.LENGTH):
    """The bank's log rows: rows_per_episode rows of every calibration episode (calibration/bank.stratified_bank with
    default_rng([20261016, seed, 2]))."""
    episodes, offsets = CB.stratified_bank(np.full(int(calibration_episodes), length),
                                           int(calibration_episodes) * int(rows_per_episode), int(rows_per_episode),
                                           np.random.default_rng([W.MASTER_SEED, int(seed), TAGS["bank"]]))
    if not np.array_equal(np.sort(episodes), np.arange(calibration_episodes)):
        raise AssertionError("the calibration bank must take rows from every calibration episode")
    return np.sort(np.concatenate([(first_episode + e) * length + o for e, o in zip(episodes, offsets)]))


def replay(log, rows=None):
    """Replay rows through the registered environment: reset(options={'state': infos/state[i]}) then
    step(actions[i]) must give observations[i] (at reset), next_observations[i], infos/next_state[i], the float32
    reward and the exact float64 reward, bit for bit. Returns counts and the first mismatches."""
    env = gym.make(log.meta["env_id"])
    rows = np.arange(log.n_rows) if rows is None else np.asarray(rows, np.int64)
    state, nstate = log["infos/state"], log["infos/next_state"]
    obs, nobs, act = log["observations"], log["next_observations"], log["actions"]
    rew, rew64 = log["rewards"], log["infos/reward64"]
    bad = dict(observation=0, next_observation=0, next_state=0, reward=0, reward64=0)
    first, mismatched = [], 0
    for i in rows:
        o0, info0 = env.reset(options={"state": state[i]})
        o1, r, _, _, info = env.step(act[i])
        checks = dict(observation=np.array_equal(o0, obs[i]) and np.array_equal(info0["state"], state[i]),
                      next_observation=np.array_equal(o1, nobs[i]), next_state=np.array_equal(info["state"], nstate[i]),
                      reward=np.float32(r) == rew[i], reward64=r == rew64[i])
        failed = [k for k, ok in checks.items() if not ok]
        for k in failed:
            bad[k] += 1
        if failed:
            mismatched += 1
            if len(first) < 5:
                first.append(dict(row=int(i), failed=failed))
    env.close()
    return dict(rows=int(len(rows)), mismatches=int(mismatched), by_field=bad, first=first)


# ------------------------------------------------------------------------------------------------ one seed

def generate_logs(seed, sizes=FULL):
    """The training-law log (with its bank rows) and the two test logs, without truth columns."""
    rec = W.HoldRecorder()
    E = sum(sizes.split_sizes)
    sim = W.draw_episodes(E, np.random.default_rng([W.MASTER_SEED, int(seed), TAGS["train_law"]]), "train", rec)
    bank = calibration_bank(seed, sizes.calibration, sizes.train, sizes.bank_rows_per_episode)
    train_log = make_log(sim, seed, "train", sizes.split_sizes, bank, TAGS["train_law"])
    tests = {}
    for tilt in ("mild", "strong"):
        tag = TAGS[f"test_{tilt}"]
        s = W.draw_episodes(sizes.test, np.random.default_rng([W.MASTER_SEED, int(seed), tag]), tilt, rec)
        tests[tilt] = make_log(s, seed, tilt, (0, 0, sizes.test), (), tag)
    return train_log, tests


def classifier_samples(seed, sizes=FULL):
    """Per sample name (train, mild, strong, train2): observations (float32), recorded commands (float32) and episode
    ids of `sizes.sample` episodes of its law. Nothing else (no rewards, next states or values)."""
    rec = W.HoldRecorder()
    out = {}
    for name, law in SAMPLE_LAWS.items():
        rng = np.random.default_rng([W.MASTER_SEED, int(seed), TAGS[f"sample_{name}"]])
        sim = W.draw_episodes(sizes.sample, rng, law, rec)
        E, L = sim["commands"].shape[:2]
        out[name] = dict(observations=sim["states"][:, :-1].astype(np.float32).reshape(E * L, TC.DX),
                         actions=sim["commands"].reshape(E * L, TC.DA),
                         episode=np.repeat(np.arange(E, dtype=np.int32), L))
    return out


def truth_rows(log, sizes=FULL, seed=None):
    """Mark M2's rows: `sizes.truth_rows` held-out (split 2) steps whose command lies outside the ball, drawn by
    default_rng([20261016, seed, 10]) and sorted, and the noise map at them."""
    seed = log.meta["seed"] if seed is None else seed
    held = log.split_rows("evaluation")
    held = held[~log["truth/in_ball"][held]]
    rng = np.random.default_rng([W.MASTER_SEED, int(seed), TAGS["truth_rows"]])
    rows = np.sort(rng.choice(held, min(sizes.truth_rows, len(held)), replace=False))
    x = log["infos/state"][rows]
    a = np.asarray(log["actions"][rows], np.float64)
    nm = TR.noise_map(x, a, W.PHYSICS, horizon=sizes.noise_map_horizon)
    return {"rows": rows.astype(np.int64), "noise_map": nm}


def d1(quad):
    """Mark D1 (spec.json) on one seed's quadrature: values, ranges and pass."""
    checks = dict(
        holds_removed=dict(value=quad["holds_removed_train"]["value"], rule=f">= {D1_HOLDS_REMOVED_MIN}",
                           ok=quad["holds_removed_train"]["value"] >= D1_HOLDS_REMOVED_MIN),
        Z=dict(value=quad["Z"]["value"], rule=f"in {list(D1_Z)}", ok=D1_Z[0] <= quad["Z"]["value"] <= D1_Z[1]))
    for tilt, (lo, hi) in D1_IN_BALL.items():
        v = quad["in_ball_share"][tilt]["value"]
        checks[f"in_ball_{tilt}"] = dict(value=v, rule=f"in {[lo, hi]}", ok=lo <= v <= hi)
    return dict(checks=checks, passes=all(c["ok"] for c in checks.values()),
                note="judged on each seed's quadrature (spec.json pass_marks D1)")


def removal_summary(log, gap):
    """What the ball removes: kept rows, leaks (kept rows inside the ball: 0) and, from the diagnostic flag, the share
    of the training split's holds it removes."""
    removal = SH.make_removal(log, "gap", gap)
    kept = removal.kept_train_rows(log)
    bank = removal.bank_rows(log)
    train = log.split_rows("train")
    hold = log.diagnostic("infos/hold")
    ing = log["truth/in_ball"]
    return dict(training_rows=int(len(train)), kept_training_rows=int(len(kept)),
                kept_share=float(len(kept) / len(train)), bank_rows=int(len(log.bank_rows)),
                kept_bank_rows=int(len(bank)), leaks_training=SH.leak_count(kept, log, gap),
                leaks_bank=SH.leak_count(bank, log, gap),
                hold_share_training=float(hold[train].mean()),
                holds_removed_training=float(ing[train][hold[train]].mean()) if hold[train].any() else None,
                removed_that_are_holds=float(hold[train][ing[train]].mean()) if ing[train].any() else None,
                held_out_in_ball_share=float(ing[log.split_rows("evaluation")].mean()))


def build_seed(seed, out, sizes=FULL, log=print):
    """Build and write one seed's files (module docstring). Returns (world record, timings)."""
    t0, times = time.perf_counter(), {}
    tick = lambda name, start: times.__setitem__(name, round(time.perf_counter() - start, 2))
    out = refuse_protected(out) / f"seed{int(seed)}"
    s = time.perf_counter()
    train_log, tests = generate_logs(seed, sizes)
    tick("logs", s)
    s = time.perf_counter()
    gap, record = SH.define_gap(train_log)
    tick("ball", s)
    if gap is None:
        raise RuntimeError(f"seed {seed}: the removal rule found no ball ({record.get('reason')})")
    train_log = train_log.with_arrays(truth_columns(train_log, gap))
    tests = {k: v.with_arrays(truth_columns(v, gap)) for k, v in tests.items()}
    s = time.perf_counter()
    samples = classifier_samples(seed, sizes)
    tick("classifier_samples", s)
    s = time.perf_counter()
    grid, curve = W.curves(gap, sizes.grid_points, sizes.per_point, (W.MASTER_SEED, int(seed), TAGS["quadrature"]))
    quad = W.quadrature(grid, curve)
    tick("quadrature", s)
    s = time.perf_counter()
    truth = truth_rows(train_log, sizes, seed)
    tick("truth_rows", s)
    s = time.perf_counter()
    replays = {"train_law": replay(train_log)}
    for k, v in tests.items():
        replays[f"test_{k}"] = replay(v)
    tick("replay", s)
    if any(r["mismatches"] for r in replays.values()):
        raise AssertionError(f"seed {seed}: replay through env.step mismatched: {replays}")
    s = time.perf_counter()
    files = {}
    about = "ThrusterChain importance-weighting log (bca-shift-work/iw/SPEC.md); see experiments/shift_iw/data.py"
    m = write_hdf5(out / "train_law.hdf5", train_log._arrays, train_log.meta, about + "; training law, all splits")
    files["train_law.hdf5"] = m["file_sha256"]
    for k, v in tests.items():
        m = write_hdf5(out / f"test_{k}.hdf5", v._arrays, v.meta, about + f"; test law '{k}'")
        files[f"test_{k}.hdf5"] = m["file_sha256"]
    flat = {f"{name}/{f}": arr for name, d in samples.items() for f, arr in d.items()}
    m = write_hdf5(out / "samples.hdf5", flat, dict(schema=SCHEMA, seed=int(seed), laws=SAMPLE_LAWS,
                                                    episodes=sizes.sample, gap=gap.as_dict()),
                   "classifier samples: observations, recorded commands and episode ids only")
    files["samples.hdf5"] = m["file_sha256"]
    m = write_hdf5(out / "truth.hdf5", truth, dict(schema=SCHEMA, seed=int(seed), sizes=sizes.as_dict()),
                   "mark M2's held-out rows outside the ball and the noise map")
    files["truth.hdf5"] = m["file_sha256"]
    tick("write", s)
    world = dict(
        schema=SCHEMA, seed=int(seed), sizes=sizes.as_dict(), master_seed=W.MASTER_SEED, tags=TAGS,
        laws={t: dict(lam=W.law_lambda(t), mean_current=W.mean_current(t), weight_constant=W.ratio_constant(t),
                      weight_slope=W.ratio_slope(t), full_test_mass=W.full_test_mass(t)) for t in W.TILT_NAMES},
        recorder=W.HOLD_SPEC.as_dict(), hold_command=W.HoldRecorder().hold.tolist(),
        gap=gap.as_dict(), gap_record=record, removal=removal_summary(train_log, gap),
        test_in_ball_share={"none": float(train_log["truth/in_ball"][train_log.split_rows("evaluation")].mean()),
                            **{k: float(v["truth/in_ball"].mean()) for k, v in tests.items()}},
        quadrature=quad, curves=dict(grid=grid.tolist(), **{k: dict(mean=v.mean(1).tolist(),
                                                                    se=(v.std(1, ddof=1) / math.sqrt(v.shape[1])).tolist())
                                                           for k, v in curve.items()}),
        D1=d1(quad), replay=replays, files=files, code_sha256=code_hashes(), spec_sha256=spec_sha256())
    digest = write_json(out / "world.json", world)
    times["total"] = round(time.perf_counter() - t0, 2)
    (out / "build.json").write_text(json.dumps(dict(seed=int(seed), seconds=times, world_json_sha256=digest),
                                               indent=1))
    log(f"seed {seed}: {train_log.n_rows} training-law rows, ball rho {gap.rho:.3f}, Z {quad['Z']['value']:.4f}, "
        f"D1 {'pass' if world['D1']['passes'] else 'FAIL'}, {times['total']:.0f}s")
    return world, times


# ------------------------------------------------------------------------------------------------ start banks

def start_banks(n=1000):
    """The fixed start banks: n starts per law from one generator (default_rng([20261016, 1000])) re-drawn per law,
    so the banks share every float and wave number and differ only in c."""
    return {t: W.draw_starts(int(n), np.random.default_rng(list(START_BANK_STREAM)), t) for t in W.TILT_NAMES}


def bank_recorder(n=1000):
    """The recording controller on a start bank with fixed noise and coin streams (default_rng([20261016, 1001]):
    noise (n, 100, 4), then coin (n, 100)); the same streams on every bank. The 0-point anchor."""
    rng = np.random.default_rng(list(RECORDER_BANK_STREAM))
    noise = rng.standard_normal((int(n), W.LENGTH, TC.DA))
    coin = rng.uniform(size=(int(n), W.LENGTH))
    return RC.StreamedRecorder(W.HoldRecorder(), noise, coin)


def anchors(banks):
    """Mean 100-step return (exact; truth.rollout) of the fixed controllers on each bank: the recording controller
    (0 points), the stall-aware controller (100 points) and normal driving only (a reference row), with standard
    errors and the reference's points."""
    out = {}
    for law, x0 in banks.items():
        n = len(x0)
        row = {}
        for name, ctrl in (("recording", bank_recorder(n)), ("stall_aware", RC.stall_aware(W.PHYSICS)),
                           ("normal_driving", RC.hand_only(physics=W.PHYSICS))):
            J = TR.rollout(ctrl, x0, W.PHYSICS).J
            row[name] = dict(mean=float(J.mean()), se=float(J.std(ddof=1) / math.sqrt(n)))
        span = row["stall_aware"]["mean"] - row["recording"]["mean"]
        row["normal_driving"]["points"] = 100.0 * (row["normal_driving"]["mean"] - row["recording"]["mean"]) / span
        out[law] = dict(row, anchor=dict(recording=row["recording"]["mean"], top=row["stall_aware"]["mean"]))
    return out


def build_start_banks(out, n=1000, log=print):
    out = refuse_protected(out)
    banks = start_banks(n)
    m = write_hdf5(out / "start_banks.hdf5", {f"starts/{k}": v for k, v in banks.items()},
                   dict(schema=SCHEMA, n=int(n), stream=list(START_BANK_STREAM),
                        recorder_stream=list(RECORDER_BANK_STREAM)),
                   "fixed evaluation starts per law, shared by all seeds and controllers")
    record = dict(schema=SCHEMA, n=int(n), file_sha256=m["file_sha256"], anchors=anchors(banks),
                  points_rule="100 (J - J_recording) / (J_stall_aware - J_recording) per law")
    write_json(out / "start_banks.json", record)
    log("start banks: " + ", ".join(f"{k} {v['recording']['mean']:.1f} / {v['stall_aware']['mean']:.1f}"
                                    for k, v in record["anchors"].items()))
    return record


# ------------------------------------------------------------------------------------------------ loading (part B)

@dataclass
class SeedData:
    """One seed's data as part B uses it. train_log and tests ('mild', 'strong') are IWLogs with truth columns;
    samples: the classifier samples; truth: mark M2's rows; world: world.json; gap: the ball (shift.Gap)."""

    seed: int
    train_log: IWLog
    tests: dict
    samples: dict
    truth: dict
    world: dict
    gap: object

    def test(self, tilt):
        """(log, rows) of a tilt's test steps: the held-out split of the training-law log for 'none', the whole test
        log otherwise."""
        if tilt == "none":
            return self.train_log, self.train_log.split_rows("evaluation")
        log = self.tests[tilt]
        return log, np.arange(log.n_rows)

    def removal(self, kind):
        """v1's removal on the training-law log: 'gap' (main) or 'none' (the full-data control)."""
        return SH.make_removal(self.train_log, kind, self.gap if kind == "gap" else None)

    def test_mass(self, tilt, gapped=True):
        """The exact scalar test mass of a tilt: E_tilt[w | outside the ball] by quadrature (gapped), or the closed
        form E_train[w^2] for the full-data control."""
        q = self.world["quadrature"]
        return q["test_mass_gapped"][tilt]["value"] if gapped else q["test_mass_full"][tilt]


def load_seed(seed, root=OUT_DEFAULT):
    root = Path(root) / f"seed{int(seed)}"
    world = read_json(root / "world.json")
    train_log = IWLog(*read_hdf5(root / "train_law.hdf5"))
    tests = {k: IWLog(*read_hdf5(root / f"test_{k}.hdf5")) for k in ("mild", "strong")}
    flat, _ = read_hdf5(root / "samples.hdf5")
    samples = {name: {f: flat[f"{name}/{f}"] for f in SAMPLE_FIELDS} for name in SAMPLE_LAWS}
    truth, _ = read_hdf5(root / "truth.hdf5")
    for name, digest in world["files"].items():
        if sha256_file(root / name) != digest:
            raise ValueError(f"{root / name}: SHA-256 differs from world.json")
    return SeedData(int(seed), train_log, tests, samples, truth, world, SH.Gap(**world["gap"]))


def load_start_banks(root=OUT_DEFAULT):
    arrays, meta = read_hdf5(Path(root) / "start_banks.hdf5")
    return {t: arrays[f"starts/{t}"] for t in W.TILT_NAMES}, read_json(Path(root) / "start_banks.json")


def normalization(data):
    """The learners' normalisation rule for both host runs of a seed: mean and SD (+ 0.001) of the float32
    observations of the gapped log's kept training rows (learners.normalization)."""
    from experiments.shift import learners as LR

    return LR.normalization(data.train_log, data.removal("gap"))


def prepare(data, kind, settings=None):
    """learners.prepare of the training-law log under removal 'gap' or 'none', normalised by the gapped rule, with
    this controller's hard-water flag as the region diagnostic (learners.prepare's own region is v1's push rule)."""
    from experiments.shift import learners as LR

    p = LR.prepare(data.train_log, data.removal(kind), normalization(data), settings)
    return replace(p, spec=data.train_log.spec, region=W.HoldRecorder().hard_water(p.states))


