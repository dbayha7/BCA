"""Evaluate the saved baselines exactly and judge gates W0 and W1 of PROTOCOL.md, Amendment 2.
NumPy only.

    python -I -B validate_published.py --label published_validation

Writes published_validation.json, records.json and published_tables.md into results/<label>/.
The score is the paper's: the chance of reaching the goal from the start cell within 200 steps,
as a share of the optimal policy's.
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import critical_env as E  # noqa: E402
import published_checks as checks  # noqa: E402
import published_collect as C  # noqa: E402

PASS_SCORE, VALID_SEEDS_NEEDED, STUDY_DATASETS = 0.90, 3, 3


def mean(values):
    return float(np.mean(values))


def best_possible(task):
    moves, value = task.best_policy()
    out = task.outcomes(E.policy_from_moves(moves))
    free = task.free_cells()
    return {"goal": float(out["goal"][task.start]), "lava": float(out["lava"][task.start]),
            "value": float(value[task.start]), "mean_goal_every_open_cell": float(out["goal"][free].mean())}


def policy_record(task, commands, q1, best):
    """Everything the gates and the tables need about one policy."""
    free = task.free_cells()
    value = task.value(commands)
    out = task.outcomes(commands)
    true_q = task.command_values(value)            # command a move once at a cell, then follow this policy
    record = {"score": float(out["goal"][task.start] / best["goal"]),
              "goal": float(out["goal"][task.start]), "lava": float(out["lava"][task.start]),
              "timeout": float(out["timeout"][task.start]),
              "value_share": float(value[task.start] / best["value"]),
              "score_from_every_open_cell": float(out["goal"][free].mean() / best["mean_goal_every_open_cell"]),
              "stalled_start_cells": int((out["timeout"][free] > 0.5).sum()),
              "mean_abs_preference": float(np.abs(commands[free]).mean()),
              "lava_by_cell": {str(cell): float(reached[task.start]) for cell, reached in out["lava_by_cell"].items()}}
    for name in checks.CRITICAL_CELLS:
        spot = checks.critical_spot(task, name)
        cell, fatal, through = spot["cell"], list(spot["fatal"]), spot["through"]
        chance = task.command_probabilities(commands[cell])
        error = q1[cell] - true_q[cell]
        record[name] = {"commands_a_fatal_move": float(chance[fatal].sum()), "commands_the_way_through": float(chance[through]),
                        "critic_error_fatal": float(error[fatal].mean()), "critic_error_through": float(error[through]),
                        "critic_rates_a_fatal_move_above_the_way_through": bool(q1[cell][fatal].max() > q1[cell][through]),
                        "critic": dict(zip(E.MOVE_NAMES, (float(x) for x in q1[cell]))),
                        "true_value": dict(zip(E.MOVE_NAMES, (float(x) for x in true_q[cell])))}
    return record


def judge(records, seeds, train_seeds, seeds_generated, seeds_passing_checks):
    """W0 from the manifest; W1 from the baselines on the `optimal` recipe, one dataset seed at a time."""
    per_seed = []
    for d in seeds:
        scores = [records[(d, "optimal", s)]["score"] for s in train_seeds]
        per_seed.append({"data_seed": d, "scores_on_optimal": scores, "valid": bool(min(scores) >= PASS_SCORE)})
    valid = [row["data_seed"] for row in per_seed if row["valid"]]
    return {"W0_data_are_what_the_paper_describes": {
                "seeds_generated": seeds_generated, "seeds_passing_every_check": seeds_passing_checks,
                "seeds_dropped": [d for d in seeds_generated if d not in seeds_passing_checks]},
            "W1_baseline_is_competent_on_optimal_data": {
                "pass_score": PASS_SCORE, "per_seed": per_seed, "valid_seeds": valid,
                "passed": len(valid) >= VALID_SEEDS_NEEDED},
            "study_datasets": valid[:STUDY_DATASETS] if len(valid) >= VALID_SEEDS_NEEDED else []}


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    return "\n".join(lines + ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]) + "\n"


def pct(x, digits=1):
    return f"{100 * x:.{digits}f}%"


def render(records, gates, seeds, train_seeds, best):
    w1 = gates["W1_baseline_is_competent_on_optimal_data"]
    doc = ["# Published map, the paper's data recipes: validation tables\n",
           "Generated by `validate_published.py`. Every number is exact for the saved policy, over 200 steps, "
           "from the start cell unless a column says otherwise. Baselines only.\n",
           f"The optimal policy reaches the goal {pct(best['goal'])} of the time and ends in lava {pct(best['lava'])}. "
           "The score is a policy's goal rate as a share of that.\n",
           "## Gates\n",
           table(["Gate", "Result", "Verdict"], [
               ["W0 the data are what the paper describes",
                f"{len(gates['W0_data_are_what_the_paper_describes']['seeds_passing_every_check'])} of "
                f"{len(gates['W0_data_are_what_the_paper_describes']['seeds_generated'])} seeds pass every check", "-"],
               ["W1 the baseline is competent on optimal data",
                f"{len(w1['valid_seeds'])} of {len(w1['per_seed'])} seeds valid (need {VALID_SEEDS_NEEDED})",
                "PASS" if w1["passed"] else "FAIL"]]),
           "## W1, one dataset seed at a time\n",
           table(["Dataset seed", "Scores on `optimal` (3 training seeds)", "Valid"],
                 [[row["data_seed"], ", ".join(f"{x:.3f}" for x in row["scores_on_optimal"]), "yes" if row["valid"] else "no"]
                  for row in w1["per_seed"]]),
           "## By recipe, all trained seeds\n"]
    rows = []
    for recipe in C.RECIPES:
        recs = [records[(d, recipe, s)] for d in seeds for s in train_seeds]
        rows.append([recipe, len(recs), f"{mean([r['score'] for r in recs]):.3f}", f"{min(r['score'] for r in recs):.3f}",
                     pct(mean([r["goal"] for r in recs])), pct(mean([r["lava"] for r in recs])),
                     pct(mean([r["timeout"] for r in recs])), f"{mean([r['value_share'] for r in recs]):.3f}",
                     f"{mean([r['score_from_every_open_cell'] for r in recs]):.3f}",
                     f"{mean([r['mean_abs_preference'] for r in recs]):.2f}"])
    doc.append(table(["Recipe", "Runs", "Score, mean", "Score, lowest", "Reaches the goal", "Ends in lava", "Times out",
                      "Discounted value, share of best", "Score from every open cell", "Command strength"], rows))
    for name, where in (("second_critical", "row 8, column 3; on the optimal route from the start"),
                        ("critical", "row 6, column 7; on the route from other start cells")):
        doc.append(f"## At the {name.replace('_', ' ')} cell ({where})\n")
        rows = []
        for recipe in C.RECIPES:
            recs = [records[(d, recipe, s)][name] for d in seeds for s in train_seeds]
            rows.append([recipe, pct(mean([r["commands_a_fatal_move"] for r in recs]), 2),
                         pct(mean([r["commands_the_way_through"] for r in recs])),
                         f"{mean([r['critic_error_fatal'] for r in recs]):+.3f}",
                         f"{mean([r['critic_error_through'] for r in recs]):+.3f}",
                         f"{sum(r['critic_rates_a_fatal_move_above_the_way_through'] for r in recs)} of {len(recs)}"])
        doc.append(table(["Recipe", "Commands a fatal move", "Commands the way through", "Critic error, fatal moves",
                          "Critic error, way through", "Runs where the critic rates a fatal move highest of the two"], rows))
    return "\n".join(doc)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--label", required=True)
    args = parser.parse_args()
    folder = HERE / "results" / args.label
    start = json.loads((folder / "START.json").read_text())
    task = E.published()
    best = best_possible(task)
    records, meta = {}, {}
    for path in sorted(folder.glob("baselines_*.json")):
        saved = json.loads(path.read_text())
        with np.load(path.with_suffix(".npz"), allow_pickle=False) as arrays:
            for run in saved["runs"]:
                key = (run["data_seed"], run["recipe"], run["train_seed"])
                records[key] = policy_record(task, arrays["commands"][run["index"]], arrays["q1"][run["index"]], best)
                meta[key] = {k: run[k] for k in ("task", "data_seed", "recipe", "train_seed", "method", "reference_ready",
                                                 "audit_bank")}
    seeds, train_seeds = sorted({k[0] for k in records}), sorted({k[2] for k in records})
    if start["data_label"] is None:
        generated = passing = seeds
    else:
        manifest = json.loads((HERE / "receipts" / f"{start['data_label']}_manifest.json").read_text())
        generated, passing = manifest["seeds"], manifest["seeds_passing_every_check"]
    gates = judge(records, seeds, train_seeds, generated, passing)
    (folder / "published_validation.json").write_text(json.dumps({"best_possible": best, **gates}, indent=1))
    (folder / "records.json").write_text(json.dumps(
        [{**meta[k], **records[k]} for k in sorted(records, key=lambda k: (k[0], C.RECIPES.index(k[1]), k[2]))], indent=1))
    (folder / "published_tables.md").write_text(render(records, gates, seeds, train_seeds, best), encoding="utf-8")
    w1 = gates["W1_baseline_is_competent_on_optimal_data"]
    print(f"optimal policy: goal {pct(best['goal'])}, lava {pct(best['lava'])}")
    print(f"W0: seeds passing every check {passing} of {generated}")
    print(f"W1: {'PASS' if w1['passed'] else 'FAIL'}; valid seeds {w1['valid_seeds']} (need {VALID_SEEDS_NEEDED})")
    for row in w1["per_seed"]:
        print(f"  seed {row['data_seed']}: " + ", ".join(f"{x:.3f}" for x in row["scores_on_optimal"])
              + ("  valid" if row["valid"] else "  NOT valid"))
    for recipe in C.RECIPES:
        recs = [records[(d, recipe, s)] for d in seeds for s in train_seeds]
        print(f"{recipe:13s} score mean {mean([r['score'] for r in recs]):.3f} lowest {min(r['score'] for r in recs):.3f}"
              f" | lava {pct(mean([r['lava'] for r in recs]))} | timeout {pct(mean([r['timeout'] for r in recs]))}"
              f" | fatal command at second critical {pct(mean([r['second_critical']['commands_a_fatal_move'] for r in recs]), 2)}"
              f" | critic error fatal {mean([r['second_critical']['critic_error_fatal'] for r in recs]):+.3f}")
    print(f"study datasets: {gates['study_datasets'] or 'none'}")


if __name__ == "__main__":
    main()
