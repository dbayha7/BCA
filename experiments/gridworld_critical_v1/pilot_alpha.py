"""Judge the pilot of PROTOCOL.md, Amendment 3, from the saved baselines. NumPy only.

    python -I -B pilot_alpha.py

Rule fixed before the pilot: use the largest alpha for which all six baselines on `optimal` data
score at least 0.90. Writes results/pilot_alpha.json and results/pilot_alpha.md.
"""
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import critical_env as E  # noqa: E402
import published_collect as C  # noqa: E402
import validate_published as V  # noqa: E402

CANDIDATES = ("2.5", "1", "0.5", "0.25", "0.1")          # as written in the result labels
PASS_SCORE, MIN_ROWS = V.PASS_SCORE, 16


def summarize(label, task, best, optimal_moves, free):
    folder = HERE / "results" / label
    if not (folder / "COMPLETE.json").exists():
        return None
    start = json.loads((folder / "START.json").read_text())
    runs = json.loads((folder / f"baselines_{task.name}.json").read_text())["runs"]
    out = {"alpha": start["alpha"], "devices": start["devices"], "recipes": {}}
    with np.load(folder / f"baselines_{task.name}.npz", allow_pickle=False) as arrays:
        for recipe in C.RECIPES:
            mine = [r for r in runs if r["recipe"] == recipe]
            scores, wrong, cells, largest, strength, usable = [], 0, 0, [], [], 0
            for r in mine:
                commands, q1 = arrays["commands"][r["index"]], arrays["q1"][r["index"]]
                scores.append(V.policy_record(task, commands, q1, best)["score"])
                data = C.generate(task, recipe, r["data_seed"])
                rows = np.bincount(data["s"], minlength=E.SIZE * E.SIZE)
                seen = free[rows[free] >= MIN_ROWS]
                wrong += int((commands.argmax(axis=1)[seen] != optimal_moves[seen]).sum())
                cells += len(seen)
                largest.append(float(np.abs(q1[free]).max()))
                strength.append(float(np.abs(commands[seen]).mean()))
                usable += bool(r["reference_ready"])
            out["recipes"][recipe] = {
                "scores": sorted(scores), "mean": float(np.mean(scores)), "lowest": float(min(scores)),
                "runs_at_the_mark": int(sum(s >= PASS_SCORE for s in scores)), "runs": len(mine),
                "cells_with_a_wrong_highest_preference": wrong, "cells_checked": cells,
                "runs_whose_critic_leaves_the_possible_range": int(sum(x > 1.5 for x in largest)),
                "largest_critic_score": float(max(largest)), "mean_command_strength": float(np.mean(strength)),
                "calibrations_usable": usable}
    return out


def main():
    task = E.published()
    best = V.best_possible(task)
    optimal_moves = C.optimal_moves(task)
    free = task.free_cells()
    results = {a: summarize(f"pilot_alpha_{a}", task, best, optimal_moves, free) for a in CANDIDATES}
    missing = [a for a, r in results.items() if r is None]
    if missing:
        sys.exit(f"not finished: {missing}")
    qualifying = [a for a in CANDIDATES
                  if results[a]["recipes"]["optimal"]["runs_at_the_mark"] == results[a]["recipes"]["optimal"]["runs"]]
    chosen = max(qualifying, key=float) if qualifying else None
    verdict = {"rule": "the largest alpha for which all six baselines on optimal data score at least 0.90",
               "candidates": [float(a) for a in CANDIDATES], "qualifying": [float(a) for a in qualifying],
               "chosen_alpha": None if chosen is None else float(chosen), "by_alpha": results}
    (HERE / "results" / "pilot_alpha.json").write_text(json.dumps(verdict, indent=1))
    lines = ["# Pilot of Amendment 3: the baseline's cloning weight\n",
             "Generated by `pilot_alpha.py`. Dataset seed 7, six training seeds, baselines only. "
             "Scores are exact for the saved policies.\n"]
    for recipe in C.RECIPES:
        lines.append(f"## `{recipe}`\n")
        rows = []
        for a in CANDIDATES:
            r = results[a]["recipes"][recipe]
            rows.append([a, f"{r['mean']:.3f}", f"{r['lowest']:.3f}", f"{r['runs_at_the_mark']} of {r['runs']}",
                         f"{r['cells_with_a_wrong_highest_preference']} of {r['cells_checked']}",
                         f"{r['runs_whose_critic_leaves_the_possible_range']} of {r['runs']}",
                         f"{r['mean_command_strength']:.2f}"])
        lines.append(V.table(["alpha", "Score, mean", "Lowest", "Runs at 0.90 or more",
                              "Cells with a wrong highest preference", "Runs whose critic leaves the possible range",
                              "Command strength"], rows))
    lines.append(f"**Rule:** {verdict['rule']}. **Qualifying:** {verdict['qualifying'] or 'none'}. "
                 f"**Chosen:** {verdict['chosen_alpha']}.\n")
    (HERE / "results" / "pilot_alpha.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
