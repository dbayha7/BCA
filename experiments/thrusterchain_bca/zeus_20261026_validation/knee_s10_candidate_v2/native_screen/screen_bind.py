"""The declared in-process changes that let knee_edge_ood_v3's Stage 1 pipeline run on candidate knee_s10_v2's
data (SCREEN_RULE.md, "What is reused and what is changed"). Imported by prepare.py (CPU) and screen_worker.py (GPU)
after `g2_formal_v2` has substituted the widened recorder. Nothing on disk in knee_edge_ood_v3 changes.

1. dataset entropy: dataset_knee validates research data against the formal G2 v2 collection entropy;
2. data-plan seeds: bindings._seeds_for returns the screen's seeds for the two formal G2 v2 datasets (by digest);
3. training seeds: stage1_worker.protocol_view returns the screen's three seed rows for research jobs;
4. the E2 start bank: stage1_eval.bank_states("stage1_e2_bank") returns the formal G2 v2's 128 E2 starts;
5. the E2 anchors: stage1_worker.anchors returns the formal G2 v2's 96 gated anchors (built by the v2 prefix rule,
   identical in both worlds) as the E2 set; the E1 set stays knee_edge_ood_v3's (reported only);
6. the BCA dose: rerun1 runtime.make_adapter gives the "bca" arm kappa = KAPPA instead of the frozen 3.0
   (the dose screen's patch);
7. the dataset loader (amendment A1): dataset_knee.load becomes screen_data.load for the two formal G2 v2 archives,
   authenticated by sha256 and the producer's sealed run record instead of regenerated by reset replay, which is not
   bit-portable from the Windows venv that collected them to the recorded Linux environment (one ULP, episode 16).
"""
import json
from pathlib import Path
import sys

import numpy as np

HERE = Path(__file__).resolve().parent
CAND = HERE.parent
F2 = CAND / "formal_g2"
V1 = CAND.parent / "knee_s10_candidate_v1"
V3 = CAND.parent / "knee_edge_ood_v3"
FORMAL_RUN = F2 / "formal_g2_run" / "attempt_1"
KAPPA = 63.0

import g2_formal_v2 as G2                                   # noqa: E402  substitutes the recorder; must come first
import g2_seeds_v2 as GS2                                   # noqa: E402
import screen_seeds as SS                                   # noqa: E402
import screen_data as SD                                    # noqa: E402
import bindings as B                                        # noqa: E402
import dataset_knee as D                                    # noqa: E402
import qpi                                                  # noqa: E402
import seeds as S                                           # noqa: E402
import stage1_eval as E                                     # noqa: E402
from core import require, sha_file                          # noqa: E402

FORMAL_REPORT = json.loads((FORMAL_RUN / "report.json").read_text(encoding="utf-8"))
COLLECTION = json.loads((FORMAL_RUN / "collection.json").read_text(encoding="utf-8"))
DIGESTS = {w: COLLECTION[w]["sha256"] for w in ("stall3", "nostall")}
DATASET_FILES = {w: FORMAL_RUN / COLLECTION[w]["path"] for w in ("stall3", "nostall")}
ENTROPY = int(GS2.load()["numpy"]["dataset_entropy"])
require(FORMAL_REPORT["headline"] == "PASS", "The formal G2 of knee_s10_v2 is not a PASS")
require(all(COLLECTION[w]["entropy"] == ENTROPY for w in DIGESTS), "Collection entropy differs from the v2 seeds")

_ORIGINAL = {"seeds_for": B._seeds_for, "bank_states": E.bank_states}


def patch_dataset_entropy():
    D._sealed_dataset_entropy = lambda: ENTROPY
    return ENTROPY


def seeds_for(dataset, test_seeds):
    """Change 2. Research data must be one of the two formal G2 v2 datasets, by digest and entropy."""
    if dataset.metadata.get("provenance") != "research":
        return _ORIGINAL["seeds_for"](dataset, test_seeds)
    require(type(dataset) is D.KneeDataset, "Research data must be a validated KneeDataset")
    require(test_seeds is None, "Research data use the screen's sealed seeds only")
    require(dataset.metadata["seed"] == ENTROPY and dataset.digest in DIGESTS.values(),
            "Research dataset is not a formal G2 v2 dataset (digest or entropy)")
    record = SS.load()
    return {k: record["numpy"][k] for k in S.DATA_NAMES}, sha_file(SS.SEEDS_PATH)


def patch_bindings():
    B._seeds_for = seeds_for
    return B


def protocol_view(job):
    """Change 3. Research jobs: the screen's seed rows; smoke jobs: the rows the job carries (as Stage 1)."""
    if job.get("provenance", "research") == "research":
        require(job.get("training_seeds") is None, "Research jobs use the screen's sealed training seeds")
        return {"seeds": SS.training_rows()}
    rows = job["training_seeds"]
    require(isinstance(rows, list) and len(rows) == 3, "Smoke jobs carry three test training-seed rows")
    return {"seeds": [dict(r) for r in rows]}


def bank_states(name, smoke_seed=None):
    """Change 4. The E2 bank of research evaluations is the formal G2 v2's; everything else is unchanged."""
    if name == "stage1_e2_bank" and smoke_seed is None:
        rows = G2.start_rows()
        require(len(rows) == 128, "The v2 E2 bank holds 128 starts")
        return np.stack([qpi.raw_anchor_state(r) for r in rows])
    return _ORIGINAL["bank_states"](name, smoke_seed)


def patch_eval():
    E.bank_states = bank_states
    return E


def v2_gated_anchors():
    """The 96 gated anchors of the formal G2 v2, rebuilt by the sealed prefix rule (P1 checked for each)."""
    items = GS2.gated_items()
    require(len(items) == 96, "Expected 96 gated anchors")
    anchors = [G2.build_anchor(i) for i in items]
    require(all(a["both_worlds_identical"] for a in anchors), "A v2 anchor differs between the worlds")
    return anchors


def anchors(original, smoke_seed=None):
    """Change 5. (E2 anchors, E1 anchors) for the evaluation: v2's gated anchors as E2 in research runs."""
    if smoke_seed is not None:
        return original(smoke_seed)
    _, e1 = original(None)
    return v2_gated_anchors(), e1


def patch_runtime(runtime, kappa=KAPPA):
    """Change 6 (the dose screen's): the bca arm's kappa. Idempotent."""
    if getattr(runtime, "_screen_kappa", None) == kappa:
        return runtime
    original = getattr(runtime, "_screen_original_make_adapter", runtime.make_adapter)

    def make_adapter(context, state, arm, k, *rest, **kw):
        return original(context, state, arm, kappa if arm == "bca" else k, *rest, **kw)
    runtime._screen_original_make_adapter = original
    runtime.make_adapter = make_adapter
    runtime._screen_kappa = kappa
    return runtime


def patch_dataset_loader():
    """Change 7. `dataset_knee.load` reads the two archives through screen_data.load (no regeneration)."""
    return SD.patch()


def load_dataset(world):
    patch_dataset_entropy()
    patch_dataset_loader()
    ds = D.load(DATASET_FILES[world])
    require(type(ds) is D.KneeDataset and ds.digest == DIGESTS[world], f"{world} dataset differs from the formal G2 record")
    return ds


def receipt():
    return {"kappa": KAPPA, "entropy": ENTROPY, "digests": dict(DIGESTS), "formal_manifest_sha256": FORMAL_REPORT["manifest_sha256"],
            "changes": ["dataset entropy", "data-plan seeds", "training seeds", "E2 bank", "E2 anchors", "bca kappa", "dataset loader"],
            "dataset_loader": SD.receipt()}
