TARGET_TAG = 1213156420   # stage-2 band.bank_scores: the target's smoothing-noise key, fold_in(refresh_key, TARGET_TAG)
CURRENT_INDEX = 10        # the water current is the 11th number of the state


def group_summary(y, q, U, mask=None):
    y, q, U = (np.asarray(v, np.float64) for v in (y, q, U))
    if mask is not None:
        m = np.asarray(mask, bool)
        y, q, U = y[m], q[m], U[m]
    n = int(len(y))
    if n == 0:
        return dict(rows=0)
    resid = np.abs(y - q)
    refused = ~np.isfinite(U)
    covered = (y >= q - U) & (y <= q + U) & ~refused       # coverage.outcomes: a refused row is never covered
    with np.errstate(divide="ignore", invalid="ignore"):
        ratio = resid / U
    return dict(rows=n, coverage=float(covered.mean()), refused_share=float(refused.mean()),
                mean_width=float(U[np.isfinite(U)].mean()) if (~refused).any() else None,
                median_width=float(np.median(U[np.isfinite(U)])) if (~refused).any() else None,
                mean_abs_residual=float(resid.mean()),
                q90_residual_over_width=float(np.quantile(ratio[np.isfinite(ratio)], 0.9)),
                mean_signed_residual=float((y - q).mean()))


def one(setting, world, seed, learn, log=print):
    t0 = time.perf_counter()
    out = dict(setting=setting, world=world, seed=int(seed))
    sd = SD.gate_seed(seed, world)                       # regenerates the log and checks it against the gate's record
    prep = SD.prepared(setting, sd, learn)               # the setting's removal, the gate's normalization
    d = SD.learner_dir(K.OUT, setting, world, seed)
    crec = SD.load_record(d / "critic.json")
    critic = SD.load_tree_checked(d / "critic.msgpack", L.critic_template(), crec["file_sha256"])
    band, brec = LP.load_v6_band(K.OUT, setting, world, seed)
    if band is None:
        out.update(failed=True, reason=brec.get("reason"))
        return out
    rec_u = brec["uniform"]
    out["recorded"] = dict(R=rec_u["R"], lambda_hat=rec_u["lambda_hat"], lambda_hpd=rec_u["lambda_hpd"],
                           unit=rec_u["unit"], U_max=rec_u["U_max"], bank_rows=rec_u["bank_rows"],
                           certified=rec_u["certified"], steps=brec["steps"])
    if int(len(prep.bank_rows)) != int(rec_u["bank_rows"]):
        raise AssertionError(f"bank rows {len(prep.bank_rows)} differ from the record's {rec_u['bank_rows']}")

    # the band's own plumbing, as v6bca.fit built it (no fit step is run: the saved band's eta_f and u_f are used)
    MC = v6bca._mc()
    B = MC.B
    args = L.make_args(learn, seed)
    config = B.bca_config()
    fixed = L.FixedController(K.CONTROLLER, prep.physics, prep.obs_mean, prep.obs_std)
    native = B.fixed_native(critic, fixed, learn.lr)
    rng, state, cal = B.initial_state(args, config, native, L.DX, L.DA)
    models = (fixed, L.CRITIC, cal)
    _rows, _keys, refresh_key = B.band_rows_and_keys(rng, prep.n, int(brec["steps"]), learn.batch_size, seed)
    R, unit = float(band.R), float(band.unit)
    out["band"] = dict(R=R, unit=unit, R_c=float(band.R_c), U_max=float(band.U_max), certified=bool(band.certified),
                       ready=bool(band.ready))

    # 1. the held-out scores, recomputed with the saved band and the refresh's own target key
    scores, eta_bank = B.bank_scores(args, models, state, prep.bank, refresh_key, band.cal_params, band.unit)
    with np.load(d / "v6_bank_scores.npz") as z:
        rec_scores, rec_eta = z["scores"], z["eta"]
    out["bank_scores_check"] = dict(equal=bool(np.array_equal(scores, rec_scores)),
                                    max_abs_difference=float(np.max(np.abs(scores - rec_scores))),
                                    eta_equal=bool(np.array_equal(eta_bank, rec_eta)),
                                    rows=int(len(scores)), share_at_most_R=float(np.mean(scores <= R)),
                                    share_at_most_lambda_hat=float(np.mean(scores <= rec_u["lambda_hat"])))

    noise_key = jax.random.fold_in(refresh_key, TARGET_TAG)

    def readout(batch):
        """y (the one-step target), q, eta_f and the width at the rows of a Transition; U by the run's width function
        and by dose.py's order of operations."""
        y = P.native_target(args, models, state.native, batch, noise_key, 1.0)
        q = L.CRITIC.apply(state.native.critic.params, batch.obs, batch.action).min(axis=-1)
        e = cal.apply(band.cal_params, batch.obs, batch.action)
        U_run = v6bca.width_rows(band, np.asarray(batch.obs), np.asarray(batch.action))
        e32 = np.asarray(e, np.float32)
        U_dose = np.float32(R) * (np.maximum(e32, np.float32(1e-6)) * np.float32(unit))   # calibration/dose.py:75-76
        return (np.asarray(y, np.float64), np.asarray(q, np.float64), np.asarray(e, np.float64),
                np.asarray(U_run, np.float64), U_dose.astype(np.float64))

    lg = sd.log
    mean, std = prep.obs_mean, prep.obs_std

    # 2./3. the calibration rows directly (|y - q| <= U), the kept training rows, the hidden training rows
    y, q, e, U, U2 = readout(prep.bank)
    out["width_order_check_bank"] = dict(max_rel_difference=float(np.max(np.abs(U - U2) / np.maximum(U, 1e-30))),
                                         equal=bool(np.array_equal(U, U2)))
    out["bank_direct"] = group_summary(y, q, U)
    y, q, e, U, U2 = readout(prep.train)
    out["train_kept"] = group_summary(y, q, U)
    out["width_order_check_train"] = dict(max_rel_difference=float(np.max(np.abs(U - U2) / np.maximum(U, 1e-30))))
    train_rows = lg.split_rows("train")
    hidden = np.setdiff1d(train_rows, prep.rows)
    if len(hidden):
        y, q, e, U, U2 = readout(L._transition(lg, hidden, mean, std))
        out["train_hidden"] = group_summary(y, q, U)
        a_h = np.asarray(lg["actions"][hidden], np.float64)
        ball_h = np.asarray(sd.gap.contains(a_h), bool)
        out["train_hidden_ball"] = group_summary(y, q, U, ball_h)
        out["train_hidden_not_ball"] = group_summary(y, q, U, ~ball_h)
    else:
        out["train_hidden"] = dict(rows=0)

    # the evaluation split: fresh rows from the recording law
    ev = lg.split_rows("evaluation")
    y, q, e, U, U2 = readout(L._transition(lg, ev, mean, std))
    acts = np.asarray(lg["actions"][ev], np.float64)
    obs_raw = np.asarray(lg["observations"][ev], np.float64)
    in_ball = np.asarray(sd.gap.contains(acts), bool)
    in_band = np.asarray(N.in_band(acts), bool)
    past80 = np.any(np.abs(acts) > TC.KNEE, axis=1)
    hidden_regions = in_ball | in_band if setting == "near80" else in_ball
    cur = obs_raw[:, CURRENT_INDEX]
    t1, t2 = np.quantile(cur, [1 / 3, 2 / 3])
    groups = {
        "all": None,
        "support": ~hidden_regions,
        "ball": in_ball,
        "band_not_ball": in_band & ~in_ball,
        "past_80": past80,
        "current_low": cur <= t1,
        "current_mid": (cur > t1) & (cur <= t2),
        "current_high": cur > t2,
        "support_current_low": ~hidden_regions & (cur <= t1),
        "support_current_mid": ~hidden_regions & (cur > t1) & (cur <= t2),
        "support_current_high": ~hidden_regions & (cur > t2),
    }
    out["evaluation"] = {g: group_summary(y, q, U, m) for g, m in groups.items()}
    out["evaluation"]["current_terciles"] = [float(t1), float(t2)]
    out["width_order_check_evaluation"] = dict(max_rel_difference=float(np.max(np.abs(U - U2) / np.maximum(U, 1e-30))))
    out["seconds"] = time.perf_counter() - t0
    log(f"{setting}/{world}/seed{seed}: R={R:.4f} u={unit:.4f} scores equal={out['bank_scores_check']['equal']} "
        f"bank<=R {out['bank_scores_check']['share_at_most_R']:.3f} | eval all {out['evaluation']['all']['coverage']:.3f}"
        f" support {out['evaluation']['support']['coverage']:.3f} ball {out['evaluation']['ball']['coverage']:.3f}"
        f" band {out['evaluation']['band_not_ball']['coverage']:.3f} past80 {out['evaluation']['past_80']['coverage']:.3f}"
        f" | train kept {out['train_kept']['coverage']:.3f} hidden {out['train_hidden'].get('coverage')} "
        f"({out['seconds']:.0f} s)")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--settings", default="near80,random_rows")
    ap.add_argument("--worlds", default="stall,no_stall")
    ap.add_argument("--seeds", default="0,1,2,3,4")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    learn = SD.gate_prereg().config.learn
    results = []
    for setting in a.settings.split(","):
        for world in a.worlds.split(","):
            for seed in (int(s) for s in a.seeds.split(",")):
                try:
                    results.append(one(setting, world, seed, learn))
                except Exception as error:  # noqa: BLE001  (one bad seed-world must not lose the others)
                    results.append(dict(setting=setting, world=world, seed=seed, failed=True,
                                        reason=f"{type(error).__name__}: {error}"))
                    print(f"{setting}/{world}/seed{seed}: FAILED {type(error).__name__}: {error}", flush=True)
                Path(a.out).write_text(json.dumps(dict(
                    written_by="docs/bca_mechanics/scripts/M6_fresh_rows.py", python=sys.version.split()[0],
                    numpy=np.__version__, jax=jax.__version__, target_tag=TARGET_TAG, results=results), indent=1))
    print("wrote", a.out)


if __name__ == "__main__":
    main()
