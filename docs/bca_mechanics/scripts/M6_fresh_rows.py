"""Module M6 (the band) on recorded ThrusterChain inputs: coverage of BCA's band at rows the band never saw.

Runs ONLY in the project's pinned environment (Python 3.10, numpy 2.2.6, jax 0.6.2 on CPU) inside the owner's clone,
because it imports the near-80 run's own code and the gate's loaders. Nothing is trained: the log of each seed is
regenerated by the gate's loader (dataset.generate, a scripted recording controller, checked against the gate's data
record), the critic and the band are read from the saved files of the near-80 run (runs/shift_explore/near80/learners/
<setting>/<world>/seed<k>/{critic.msgpack, v6_band.msgpack, v6_bank_scores.npz}), and every number below is the saved
band applied to recorded rows.

    cd /home/user/bca
    JAX_PLATFORMS=cpu PYTHONDONTWRITEBYTECODE=1 /tmp/claude-0/bcavenv/bin/python -u M6_fresh_rows.py \
        --settings near80,random_rows --worlds stall,no_stall --seeds 0,1,2,3,4 --out M6_fresh_rows_coverage.json

What it computes for one seed-world (one saved band: threshold R, unit u_f, error-size network eta_f):
  1. the held-out scores |y - q| / (u_f max(eta_f, 1e-6)) at the calibration rows (the "bank"), with the band's own
     target key, compared with the recorded v6_bank_scores.npz (a plumbing check: they must be equal);
  2. the width U(s, a) = R u_f max(eta_f(s, a), 1e-6) by the run's own width function (stage-2 band.width_uniform
     through v6bca.width_rows) and by calibration/dose.py's order of operations (R * (max(eta, 1e-6) * u_f)), float32;
  3. coverage = share of rows with q - U <= y <= q + U, where y is the critic's own one-step target (reward plus the
     discounted target-critic value at the next state under the recording controller's next command with TD3's
     smoothing noise, td3_bc_bca.native_target) and q = min(Q1, Q2)(s, a), at:
       - the calibration rows (in-sample for the threshold: must be >= 0.90 by construction),
       - the kept training rows (in-sample for the critic),
       - the training rows the removal hid from the critic and the band (the ball, and in the near-80 setting also the
         70-90% throttle band),
       - the evaluation split (episodes 700-999 of the log: never trained on, never calibrated on; the same recording
         law), overall and by region: the recorded support (outside the ball and the hidden band), inside the ball,
         inside the hidden band (not in the ball), past 80% throttle on any thruster, and by tercile of the water
         current (state index 10).
  Per group: rows, coverage, mean and median width U, mean |y - q|, the 90% quantile of |y - q| / U (1.0 means the
  band is exactly calibrated for that group), and the share of refused rows (U not finite; 0 here).
"""
