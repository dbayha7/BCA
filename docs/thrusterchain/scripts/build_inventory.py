"""Build the occurrence inventory (markdown) from notes/page_text.txt (read-only on the page).

Writes notes/_inventory.md: for each label group, every sentence that uses it, with
its section id and nearest element id. Run extract_text.py first.
"""
import re
from collections import OrderedDict

BASE = "/mnt/c/Users/David/dev/bca-shift-work/page/notes/"
TEXT = BASE + "page_text.txt"
OUT = BASE + "_inventory.md"

GROUPS = OrderedDict([
    ("A. Harm-check codes H1-H4", r"\bH[1-4]\b"),
    ("B. \"the gate\"", r"\bgate(?:'s|s)?\b"),
    ("C. World-check codes T1-T9 and \"world card\"", r"\bT[1-9]\b|world card"),
    ("D. Detection codes D1-D3", r"\bD[1-3]\b"),
    ("E. Actor-check codes C1-C3, \"level 1/2\", numbered verdicts",
     r"\bC[1-3]\b|\b[Ll]evels? [12]\b|\blevel-1\b|\bverdicts? \d"),
    ("F. Other codes: A1, B1, P2-P4, stage0, list letter (a)", r"\b(?:A1|B1|P[2-4])\b|stage0|in \(a\)"),
    ("G. \"room\", \"room-certified\", \"certified\"", r"\broom\b|room-certified|\bcertif\w*"),
    ("H. \"arm\" / \"arms\"", r"\barms?\b"),
    ("I. Critic nicknames: gapped / full-data / full critic; \"gap\" in the weighting test",
     r"\bgapped\b|full-data critic|\bfull critic\b|action gap|after the gap|outside the gap|the gap costs"),
    ("J. Numbered cross-references and cards: shift card, column N, measure N, Setting N, Claim N",
     r"shift card|shift-card|\bcolumns? \d\b|\bmeasure \d\b|\bSetting [123]\b|\bClaim [12]\b"),
    ("K. \"alpha ladder\", \"ladder\", \"retune\"", r"ladder|retune"),
    ("L. \"the design\" (as a noun), \"scout\", \"Spec\", \"protocol\", \"the user\"",
     r"\b[Tt]he design\b(?! of)|\bdesign's\b|\bscout\b|\b[Ss]pec\b|\bprotocol\b|\bthe user(?:'s)?\b|[Uu]ser's go-ahead"),
    ("M. Caution nicknames: harm-placed vs over-preference-placed, even caution, cap-2, edge-slope",
     r"harm-placed|over-preference-placed|cap-2|[Ff]actors up to 2|\b[Ee]ven (?:caution|⟦math|×|multiplier)|strength-matched even|edge-slope|edge slope|bending critic"),
    ("N. Acronyms and jargon with a first-use or definition problem",
     r"BCA test environments|\bLQ\b|\bUTC\b|\bCPUs?\b|CPU-hours|wall clock|\bcores\b|\b\d(?:\.\d)?(?:–\d)? h\b|\bJSON\b|numpy|\btanh\b|[Pp]olicy optimisation|[Rr]ank correlation|[Pp]robability density|\bdensity\b|classifier|Holm family|one-sided 95% over seeds|calibration bank|build checks|commit [0-9a-f]{7}|importance weighting|reported, not gated|not gated"),
    ("O. \"Time step\" wording and shorthand readouts in the live panel",
     r"[Tt]ime step|region above 0\.565|thruster-steps"),
])


def sentences(t):
    parts = re.split(r"(?<=[.!?;])\s+(?=[A-Z0-9(\"“])", t)
    return [p.strip() for p in parts if p.strip()]


def clean(s):
    s = s.replace("¦", "|").strip()
    s = re.sub(r"^\|\s*", "", s)
    s = re.sub(r"⟦math: (.*?)⟧", r"$\1$", s)
    return s


def main():
    rows = []
    for line in open(TEXT, encoding="utf-8"):
        m = re.match(r"\[([^|]*) \| ([^\]]*)\] (.*)", line.rstrip("\n"))
        if m:
            rows.append(m.groups())
    # add the JS-built strings of the live panel readouts
    js = open(BASE + "js_strings.txt", encoding="utf-8").read().splitlines()
    for l in js:
        m = re.match(r"L(\d+): (.*)", l)
        if m and not m.group(2).startswith("<skipped"):
            rows.append(("script", "L" + m.group(1), m.group(2)))
    out = ["## Appendix: every occurrence, by label group", "",
           "Each line: `section id` (nearest element id) followed by the sentence, as a reader sees it. "
           "Math is shown as its spoken label between dollar signs. Generated by scripts/build_inventory.py "
           "from notes/page_text.txt (scripts/extract_text.py).", ""]
    for title, pat in GROUPS.items():
        rx = re.compile(pat)
        hits, seen = [], set()
        for sec, near, t in rows:
            for s in sentences(t):
                if not rx.search(s):
                    continue
                c = clean(s)
                if len(c) > 330:
                    k = rx.search(c).start() if rx.search(c) else 0
                    a = max(0, k - 140)
                    c = ("… " if a else "") + c[a:a + 330] + " …"
                key = (sec, c)
                if key in seen:
                    continue
                seen.add(key)
                where = f"`#{sec}`" if sec not in ("(top)", "script") else ("`#top` (at-a-glance)" if sec == "(top)" else "`<script>`")
                nid = f" ({near})" if near and near != sec else ""
                hits.append(f"- {where}{nid}: {c}")
        out.append(f"### {title} ({len(hits)})")
        out.append("")
        out.extend(hits if hits else ["- none"])
        out.append("")
    open(OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("\n".join(l for l in out if l.startswith("### ")))


main()
