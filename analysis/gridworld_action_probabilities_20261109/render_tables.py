"""Turn the three JSON outputs into one readable Markdown file of tables.

Usage:
    python -I -B render_tables.py --out <outputs folder>
"""
import argparse
import json
import statistics
from pathlib import Path

ARM_NAMES = {"full": "complete data", "dangerous_actions": "danger commands removed (targeted)",
             "random_rows": "random removal (control)", "fragments": "bridge rows removed (targeted)"}
HONEYPOT_ARMS = ("full", "dangerous_actions", "random_rows")
BOTTLENECK_ARMS = ("full", "fragments", "random_rows")
TARGET_NAMES = {
    "B_enter_bridge": "at B, step right onto the bridge", "B_hazard_up": "at B, step up into the hazard",
    "B_retreat": "at B, step down or left (retreat)", "gate_exit_to_C": "on the bridge, step right to C",
    "gate_back_to_B": "on the bridge, step back left to B", "gate_wall_bump": "on the bridge, bump a wall (up or down)",
    "C_wall_bump_up": "at C, bump the wall above", "C_back_into_gate": "at C, step back onto the bridge",
    "C_onward": "at C, move on (right or down)"}


def pct(x, digits=2):
    return f"{100 * x:.{digits}f}%"


def pp(x, digits=2):
    return f"{100 * x:+.{digits}f}"


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    s = json.loads((args.out / "summary.json").read_text())
    e = json.loads((args.out / "design_evidence.json").read_text())
    c = json.loads((args.out / "sharpening_counterfactual.json").read_text())["summary"]
    floor, ceiling = s["probability_floor_and_ceiling"]["2.0"]
    doc = ["# Tables: movement probabilities of the 108 archived policies\n",
           "Generated by `render_tables.py` from `summary.json`, `design_evidence.json` and "
           "`sharpening_counterfactual.json`. Every probability is per executed step at the original "
           "execution setting (beta 2) unless a column says otherwise. \"Change\" is BCA minus its matched "
           "baseline, in percentage points. One direction can never get less than "
           f"{pct(floor)} or more than {pct(ceiling)} per step.\n"]

    # ---- Honeypot --------------------------------------------------------------
    h = s["honeypot"]["dangerous_action_24_down"]
    oracle24 = e["oracle_headroom"]["honeypot"]["cells"]["24"]["oracle_step_hazard_probability"]
    doc.append("## H1. Honeypot: probability of stepping DOWN from cell 24 into the hazard\n")
    rows = []
    for arm in HONEYPOT_ARMS:
        v = h[arm]
        native = [p["native_p"] for p in v["per_pair"]]
        bca = [p["bca_p"] for p in v["per_pair"]]
        sharp = c["honeypot"][arm]["p_down_at_24"]["sharpened_native_mean"]
        rows.append([ARM_NAMES[arm], pct(v["native_mean"]), pct(statistics.median(native)), pct(v["bca_mean"]),
                     pct(statistics.median(bca)), pp(v["delta"]["mean"]), f"{v['delta']['n_negative']}/9", pct(sharp)])
    doc.append(table(["Data arm", "Baseline mean", "Baseline median", "BCA mean", "BCA median",
                      "Mean change (pp)", "Pairs lower", "Sharpened baseline mean"], rows))
    doc.append(f"Best possible policy at cell 24: {pct(oracle24)} per step. Absolute floor: {pct(floor)}.\n")
    doc.append("### H1a. Every pair\n")
    rows = []
    for arm in HONEYPOT_ARMS:
        for p in h[arm]["per_pair"]:
            rows.append([ARM_NAMES[arm], p["dataset"], p["seed"], pct(p["native_p"]), pct(p["bca_p"]),
                         pp(p["delta"]), f"{p['own_preference_term']:+.3f}", f"{p['competition_term']:+.3f}", p["verdict"]])
    doc.append(table(["Data arm", "Dataset", "Seed", "Baseline", "BCA", "Change (pp)",
                      "From lowering DOWN itself (log)", "From other directions gaining (log)", "Verdict"], rows))
    doc.append("The two log columns add up to the change in log-probability of DOWN. The first is the part "
               "that comes from pushing the DOWN preference lower; the second is the part that comes from the "
               "other directions getting more weight.\n")

    doc.append("### H1b. Other execution settings\n")
    rows = []
    for beta, block in s["honeypot"]["dangerous_action_24_down_by_beta"].items():
        for arm in HONEYPOT_ARMS:
            v = block[arm]
            rows.append([beta, ARM_NAMES[arm], pct(v["native_mean"], 3), pct(v["bca_mean"], 3),
                         pp(v["delta"]["mean"], 3), f"{v['delta']['n_negative']}/9"])
    doc.append(table(["Beta", "Data arm", "Baseline mean", "BCA mean", "Mean change (pp)", "Pairs lower"], rows))

    doc.append("## H2. Honeypot: is the drop specific to the hazard direction?\n")
    doc.append("At cell 24, UP and RIGHT make progress, DOWN is the hazard, LEFT is a harmless step back. "
               "If BCA specifically avoided danger, DOWN would fall relative to LEFT.\n")
    rows = []
    for arm in HONEYPOT_ARMS:
        m = s["honeypot"]["specificity_at_24"][arm]["mean"]
        rows.append([ARM_NAMES[arm], f"{pct(m['native_down'])} -> {pct(m['bca_down'])}",
                     f"{pct(m['native_left'])} -> {pct(m['bca_left'])}",
                     f"{pct(m['native_up_plus_right'])} -> {pct(m['bca_up_plus_right'])}",
                     f"{m['native_down_preference']:.3f} -> {m['bca_down_preference']:.3f}",
                     f"{m['native_down_over_left']:.2f} -> {m['bca_down_over_left']:.2f}",
                     f"{s['honeypot']['specificity_at_24'][arm]['pairs_where_down_over_left_fell']}/9"])
    doc.append(table(["Data arm", "DOWN (hazard)", "LEFT (harmless)", "UP + RIGHT (progress)",
                      "DOWN preference (bound is -1)", "DOWN divided by LEFT", "Pairs where that ratio fell"], rows))

    doc.append("## H3. Honeypot: all 16 cells next to a hazard\n")
    doc.append("Probability of the one direction that enters the hazard. Cells are grouped only by geometry: "
               "the hazard lies toward the goal corner (up or right of the cell) or away from it (down or left).\n")
    rows = []
    for arm in HONEYPOT_ARMS:
        for group, name in (("toward_goal_corner", "hazard toward the goal"), ("away_from_goal_corner", "hazard away from the goal")):
            v = s["honeypot"]["hazard_direction_probability_all_16_frontier_cells"][arm][group]
            k = c["honeypot"][arm]["hazard_" + group]
            rows.append([ARM_NAMES[arm], name, pct(v["native_mean"]), pct(v["bca_mean"]), pp(v["delta"]["mean"]),
                         f"{v['delta']['n_positive']}/{v['delta']['n']}", pp(v["delta"]["max"]),
                         pct(k["sharpened_native_mean"]), pp(k["largest_rise_under_sharpening"])])
    doc.append(table(["Data arm", "Group (8 cells x 9 pairs)", "Baseline mean", "BCA mean", "Mean change (pp)",
                      "Cases where BCA raised it", "Largest BCA rise (pp)", "Sharpened baseline mean",
                      "Largest rise under sharpening (pp)"], rows))
    doc.append("### H3a. Cell by cell, targeted arm\n")
    rows = []
    for group in ("toward_goal_corner", "away_from_goal_corner"):
        for cell, v in s["honeypot"]["hazard_direction_probability_all_16_frontier_cells"]["dangerous_actions"][group]["by_cell"].items():
            rows.append([cell, v["hazard_direction"], group.replace("_", " "), pct(v["native_mean"]), pct(v["bca_mean"]),
                         pp(v["delta"]["mean"]), f"{v['delta']['n_negative']}/9", pp(v["delta"]["min"]), pp(v["delta"]["max"])])
    doc.append(table(["Cell", "Hazard direction", "Group", "Baseline mean", "BCA mean", "Mean change (pp)",
                      "Pairs lower", "Best pair (pp)", "Worst pair (pp)"], rows))

    # ---- Bottleneck ------------------------------------------------------------
    b = s["bottleneck"]
    doc.append("## B1. Bottleneck: probabilities at B (cell 44), the bridge (45) and C (46)\n")
    rows = []
    for label, name in TARGET_NAMES.items():
        for arm in BOTTLENECK_ARMS:
            v = b[label][arm]
            rows.append([name, ARM_NAMES[arm], pct(v["native_mean"]), pct(v["bca_mean"]), pp(v["delta"]["mean"]),
                         f"{v['delta']['n_positive']}/9", f"{v['delta']['n_negative']}/9",
                         pp(v["delta"]["min"], 1), pp(v["delta"]["max"], 1)])
    doc.append(table(["What the policy does", "Data arm", "Baseline mean", "BCA mean", "Mean change (pp)",
                      "Pairs higher", "Pairs lower", "Min change", "Max change"], rows))
    doc.append("### B1a. Every targeted pair\n")
    per = {label: {(p["dataset"], p["seed"]): p for p in b[label]["fragments"]["per_pair"]}
           for label in ("B_enter_bridge", "B_hazard_up", "gate_exit_to_C", "C_wall_bump_up")}
    chain = {(p["dataset"], p["seed"]): p for p in b["bridge_from_B"]["fragments"]["per_pair"]}
    rows = []
    for key in sorted(chain):
        cells = [f"{pct(per[l][key]['native_p'], 1)} -> {pct(per[l][key]['bca_p'], 1)}" for l in per]
        k = chain[key]
        rows.append([key[0], key[1], *cells,
                     f"{pct(k['native_goal_200'], 1)} -> {pct(k['bca_goal_200'], 1)}",
                     f"{pct(k['native_hazard_200'], 1)} -> {pct(k['bca_hazard_200'], 1)}"])
    doc.append(table(["Dataset", "Seed", "B: right onto bridge", "B: up into hazard", "Bridge: right to C",
                      "C: bump wall above", "Goal within 200 steps from B", "Hazard within 200 steps from B"], rows))
    doc.append("### B1b. First visit to the bridgehead\n")
    doc.append("Starting at B, the chance of stepping out onto C before leaving the two cells {B, bridge} any "
               "other way, and the chance of stepping up into the hazard first.\n")
    rows = []
    for arm in BOTTLENECK_ARMS:
        m = b["bridge_from_B"][arm]["mean"]
        rows.append([ARM_NAMES[arm], f"{pct(m['native_first_visit_cross'], 1)} -> {pct(m['bca_first_visit_cross'], 1)}",
                     f"{pct(m['native_first_visit_hazard'], 1)} -> {pct(m['bca_first_visit_hazard'], 1)}",
                     f"{pct(m['native_goal_200'], 1)} -> {pct(m['bca_goal_200'], 1)}",
                     f"{pct(m['native_hazard_200'], 1)} -> {pct(m['bca_hazard_200'], 1)}"])
    doc.append(table(["Data arm", "Crosses first", "Hazard first", "Goal within 200 steps", "Hazard within 200 steps"], rows))

    # ---- Sharpening -------------------------------------------------------------
    doc.append("## S1. How much of BCA's change does plain sharpening of the baseline reproduce?\n")
    doc.append("The sharpened baseline is the saved baseline policy with every command multiplied by one number "
               "(clipped to the allowed range) so that it is as saturated as its BCA partner. No training.\n")
    names = {"p_down_at_24": "Honeypot: DOWN at 24", "goal_200_from_24": "Honeypot: goal from 24",
             "p_right_at_B": "Bottleneck: right at B", "p_up_hazard_at_B": "Bottleneck: up into hazard at B",
             "p_right_at_gate": "Bottleneck: right on the bridge", "p_up_wall_at_C": "Bottleneck: wall bump at C",
             "goal_200_from_44": "Bottleneck: goal from B", "goal_200_from_90": "Bottleneck: goal from A"}
    rows = []
    for scenario, arms in (("honeypot", HONEYPOT_ARMS), ("bottleneck", BOTTLENECK_ARMS)):
        for name, label in names.items():
            for arm in arms:
                v = c[scenario][arm].get(name)
                if v:
                    share = v["share_of_bca_mean_change_reproduced"]
                    rows.append([label, ARM_NAMES[arm], pct(v["native_mean"]), pct(v["sharpened_native_mean"]),
                                 pct(v["bca_mean"]), "n/a" if share is None else f"{100 * share:.0f}%"])
    doc.append(table(["Readout", "Data arm", "Baseline", "Sharpened baseline", "BCA",
                      "Share of BCA's mean change reproduced"], rows))

    doc.append("## S2. BCA makes every policy more decisive\n")
    rows = []
    for scenario, arms in (("honeypot", HONEYPOT_ARMS), ("bottleneck", BOTTLENECK_ARMS)):
        for arm in arms:
            d = s["decisiveness_over_all_free_cells"][scenario][arm]
            rows.append([scenario, ARM_NAMES[arm],
                         f"{pct(d['mean_top_probability']['native_mean'], 1)} -> {pct(d['mean_top_probability']['bca_mean'], 1)}",
                         f"{pct(d['share_of_preferences_at_bound']['native_mean'], 0)} -> {pct(d['share_of_preferences_at_bound']['bca_mean'], 0)}",
                         f"{d['mean_abs_preference']['pairs_where_bca_higher']}/9"])
    doc.append(table(["Task", "Data arm", "Average probability of the favorite direction",
                      "Share of preferences pinned at a bound", "Pairs where BCA is more saturated"], rows))

    # ---- Width --------------------------------------------------------------------
    doc.append("## W1. Did the width grow where the data were removed?\n")
    doc.append("Width at one fixed command, divided by that model's average width over all cells and corner "
               "commands (so 1.00 means typical). \"Critic error\" is the critic's value minus the true value of "
               "taking that command once and then following the model's own policy.\n")
    labels = {"honeypot|state24_dangerous_command": "Honeypot, cell 24, dangerous command",
              "honeypot|state24_safe_command": "Honeypot, cell 24, safe command",
              "bottleneck|B_enter_bridge_command": "Bottleneck, B, step-right command",
              "bottleneck|B_hazard_command": "Bottleneck, B, step-up (hazard) command",
              "bottleneck|gate_exit_command": "Bottleneck, bridge, step-right command",
              "bottleneck|C_onward_command": "Bottleneck, C, step-right command"}
    rows = []
    for key, label in labels.items():
        for arm, arm_name in (("native_aux", "baseline"), ("bca_direct", "BCA")):
            block = e["fixed_action_bank"]["width_at_deleted_region"][f"{key}|{arm}"]
            for condition, v in block.items():
                rows.append([label, arm_name, ARM_NAMES[condition], f"{v['mean_width']:.2f}",
                             f"{v['mean_width_relative_to_model_average']:.2f}", f"{v['mean_q1_error']:+.2f}",
                             f"{100 * v['share_where_abs_error_exceeds_3_widths']:.0f}%"])
    doc.append(table(["Probe", "Model", "Data arm", "Width", "Relative width", "Critic error",
                      "Runs where the error is bigger than 3 widths"], rows))

    doc.append("## W2. Honeypot: the width is smaller for commands that head into a hazard\n")
    rows = []
    for key, v in sorted(e["fixed_action_bank"]["width_by_corner"].items()):
        scenario, condition, arm = key.split("|")
        rows.append([scenario, ARM_NAMES[condition], "baseline" if arm == "native_aux" else "BCA",
                     f"{v['hazard_cells_mean_width_hazard_preferred_minus_avoided']:+.2f}",
                     f"{100 * v['hazard_cells_share_where_preferring_hazard_has_smaller_width']:.0f}%",
                     f"{v['hazard_cells_mean_width_other_direction_preferred_minus_avoided']:+.2f}",
                     f"{v['mean_width_at_oracle_corner']:.2f} vs {v['mean_width_over_all_corners']:.2f}"])
    doc.append(table(["Task", "Data arm", "Model", "Width change when a command prefers the hazard direction",
                      "Cases where preferring the hazard gives the smaller width",
                      "Same contrast for the three non-hazard directions",
                      "Width at the best command vs average over all corner commands"], rows))

    doc.append("## V1. True value gap versus the critic's gap\n")
    rows = []
    for key, v in sorted(e["fixed_action_bank"]["value_gaps"].items()):
        scenario, condition, arm, which = key.split("|")
        rows.append(["Honeypot 24: safe minus dangerous" if scenario == "honeypot" else "Bottleneck B: right minus up (hazard)",
                     ARM_NAMES[condition], "baseline" if arm == "native_aux" else "BCA",
                     f"{v['gap_true_q_own_policy']['mean']:.2f}", f"{v['gap_q1']['mean']:.2f}",
                     f"{v['gap_q1']['min']:.2f}", f"{v['gap_q1']['n_positive']}/9",
                     f"{v['gap_q1_minus_3w']['mean']:.2f}", f"{v['gap_q1_minus_3w']['n_positive']}/9",
                     f"{v['second']['q1_error']:+.2f}"])
    doc.append(table(["Comparison", "Data arm", "Model", "True gap", "Critic gap (mean)", "Critic gap (smallest)",
                      "Runs with the right order", "Gap after subtracting 3 widths", "Runs with the right order",
                      "Critic error on the bad command"], rows))

    # ---- Data and layout ------------------------------------------------------------
    doc.append("## D1. What data surround the bridge\n")
    rows = []
    for seed in ("1234", "2234", "3234"):
        for arm in BOTTLENECK_ARMS:
            v = e["bottleneck_data_support"][seed][arm]
            rows.append([seed, ARM_NAMES[arm], v["rows"], v["rows_left_of_wall"], v["rows_right_of_wall"],
                         v["rows_at_source"]["44"], v["rows_at_source"]["45"], v["rows_at_source"]["46"],
                         v["rows_from_B_into_hazard_34"], v["rows_arriving_at_B"]])
    doc.append(table(["Dataset", "Data arm", "All rows", "Rows left of the wall", "Rows right of the wall",
                      "Rows starting at B", "Rows starting on the bridge", "Rows starting at C",
                      "Rows that show B -> hazard", "Rows that arrive at B"], rows))

    doc.append("## D2. Where could the opening sit? (geometry and best-possible policy only)\n")
    rows = []
    for row, v in e["candidate_bottleneck_layouts"].items():
        if not v["usable"]:
            continue
        rows.append([row + (" (archived)" if row == "4" else ""), v["B"], v["C"],
                     ", ".join(v["hazard_next_to"]) or "none",
                     "; ".join(f"{cell}: {'+'.join(dirs)}" for cell, dirs in v["oracle_preferred_at_supported_neighbors_of_B"].items()),
                     ", ".join(v["neighbors_that_point_into_a_hazard_if_copied_at_B"]) or "none",
                     pct(v["oracle_goal_200_from_A90"]), pct(v["oracle_hazard_200_from_A90"])])
    doc.append(table(["Opening on row", "B", "C", "Hazard next to", "Best command at B's neighbors",
                      "Neighbors whose command, copied at B, enters a hazard",
                      "Best possible goal rate from A", "Best possible hazard rate from A"], rows))

    doc.append("## N1. How much these probabilities move with no meaningful intervention\n")
    n = e["noise_yardstick_percentage_points_as_fraction"]
    rows = [["Baseline, same dataset and seed, different Honeypot data arm, cells whose rows are identical",
             n["native_aux_between_arm_gap_at_untouched_cells"]["comparisons"],
             pp(n["native_aux_between_arm_gap_at_untouched_cells"]["median"]).lstrip("+"),
             pp(n["native_aux_between_arm_gap_at_untouched_cells"]["p90"]).lstrip("+")],
            ["BCA minus baseline at those same cells (absolute size)",
             n["bca_minus_native_absolute_shift_untouched_cells"]["comparisons"],
             pp(n["bca_minus_native_absolute_shift_untouched_cells"]["median"]).lstrip("+"),
             pp(n["bca_minus_native_absolute_shift_untouched_cells"]["p90"]).lstrip("+")],
            ["BCA minus baseline at cell 24 (absolute size)",
             n["bca_minus_native_absolute_shift_cell_24"]["comparisons"],
             pp(n["bca_minus_native_absolute_shift_cell_24"]["median"]).lstrip("+"),
             pp(n["bca_minus_native_absolute_shift_cell_24"]["p90"]).lstrip("+")]]
    doc.append(table(["Comparison", "Count", "Median gap (pp)", "90th percentile (pp)"], rows))

    (args.out / "tables.md").write_text("\n".join(doc), encoding="utf-8")
    print("wrote", args.out / "tables.md")


if __name__ == "__main__":
    main()
